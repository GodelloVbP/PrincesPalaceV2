                        new UiVec(DossierLayout.ContentCWidth, DossierLayout.StatRowHeight - 2f),
                        Place.At(cx, y))
                    .Inactive().AsDecor();

                var name = Ui.Label($"DossierStatName{i}", SheetStats.LabelFor(stat),
