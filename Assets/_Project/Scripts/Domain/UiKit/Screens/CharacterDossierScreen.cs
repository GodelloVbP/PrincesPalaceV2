        private UiNode BuildRail()
        {
            var children = new List<UiNode>();

            var portrait = Ui.Sprite("DossierPortrait", PortraitKey,
                    new UiVec(DossierLayout.PortraitSize, DossierLayout.PortraitSize),
                    Place.At(0f, DossierLayout.PortraitCentreY))
                .Coloured("#6640884D")
                .AsDecor();
            Portrait = portrait;
            children.Add(portrait);

            var name = Words("DossierName", UiString.Runtime,
                    new UiVec(DossierLayout.RailWidth, DossierLayout.NameHeight), 28, Text,
                    Place.At(0f, DossierLayout.NameCentreY), TypographyRole.Body, UiTextAlign.Centre)
                .Truncated();
            CharacterName = name;
            children.Add(name);

            var level = Words("DossierLevel", UiString.Runtime,
                new UiVec(DossierLayout.RailWidth, DossierLayout.LevelHeight), 20, TextSecondary,
                Place.At(0f, DossierLayout.LevelCentreY), TypographyRole.Body, UiTextAlign.Centre);
            LevelLine = level;
            children.Add(level);

            children.Add(Ui.Solid("DossierXpTrack", "#C8B4DE24",
                    new UiVec(DossierLayout.XpTrackWidth, DossierLayout.XpTrackHeight),
                    Place.At(0f, DossierLayout.XpTrackCentreY))
                .AsDecor());

            // Grows from the track's left edge: a left pivot and a width, never
            // anchors, which would be measured against the rail.
            var fill = Ui.Solid("DossierXpFill", Gold,
                    new UiVec(DossierLayout.XpTrackWidth, DossierLayout.XpTrackHeight),
                    Place.At(-DossierLayout.XpTrackWidth * 0.5f, DossierLayout.XpTrackCentreY, new UiVec(0f, 0.5f)))
                .AsDecor();
            XpFill = fill;
            children.Add(fill);

            var remaining = Words("DossierXpRemaining", UiString.Runtime,
                new UiVec(DossierLayout.RailWidth, DossierLayout.XpLabelHeight), 20, TextMuted,
                Place.At(0f, DossierLayout.XpLabelCentreY), TypographyRole.Body, UiTextAlign.Centre);
            XpRemaining = remaining;
            children.Add(remaining);

            children.Add(Ui.Solid("DossierIdentityRule", Rule, new UiVec(DossierLayout.RailWidth, 1f),
                Place.At(0f, DossierLayout.IdentityRuleY)).AsDecor());

            for (int i = 0; i < CharacterSections.All.Length; i++)
            {
                children.Add(BuildSectionRow(i));
            }

            return Ui.Panel("DossierRail", Place.At(DossierLayout.RailCentreX, DossierLayout.BodyCentreY),
                UiSize.Fixed(DossierLayout.RailWidth, DossierLayout.BodyHeight), children);
        }

        private UiNode BuildSectionRow(int index)
        {
            float width = DossierLayout.RailWidth;
            float height = DossierLayout.SectionRowHeight;
            float textWidth = width - DossierLayout.SectionInset * 2f - DossierLayout.SectionPipSize - 8f;

            var bar = Ui.Solid($"DossierSection{index}Bar", MarkerDark,
                    new UiVec(DossierLayout.SectionBarWidth, DossierLayout.SectionBarHeight),
                    Place.At(-width * 0.5f + DossierLayout.SectionBarWidth * 0.5f, 0f))
                .AsDecor();

            // Caption, NOT Label: UiEmitter names a button's own text
            // "<button>Label", and a child by that name collides with it.
            var caption = Words($"DossierSection{index}Caption", CharacterSections.Label(CharacterSections.All[index]),
                new UiVec(textWidth, DossierLayout.SectionLabelHeight), 24, TextSecondary,
                Place.At(-width * 0.5f + DossierLayout.SectionInset + textWidth * 0.5f, 0f),
                TypographyRole.FunctionalHeading, UiTextAlign.Left);

            // Attention (plan C20): lit by CharacterAttention when this
            // section is what the character is owed.
            var pip = Ui.Sprite($"DossierSection{index}Pip", "proc:solid_circle",
                    new UiVec(DossierLayout.SectionPipSize, DossierLayout.SectionPipSize),
                    Place.At(width * 0.5f - DossierLayout.SectionInset - DossierLayout.SectionPipSize * 0.5f, 0f))
                .Coloured(Gold)
                .AsDecor()
                .Inactive();

            var rule = Ui.Solid($"DossierSection{index}Rule", Rule, new UiVec(width, 1f),
                Place.At(0f, -height * 0.5f + 0.5f)).AsDecor();

            var row = Ui.Button($"DossierSection{index}", UiString.Runtime, new UiVec(width, height), 24,
                    Place.At(0f, DossierLayout.SectionRowCentreY(index)))
                .NoChrome()
                .Quiet()
                .Styled(TypographyRole.FunctionalHeading);
            row.Children.Add(rule);
            row.Children.Add(bar);
            row.Children.Add(caption);
            row.Children.Add(pip);

            SectionRows.Add(row);
            SectionCaptions.Add(caption);
            SectionBars.Add(bar);
            SectionPips.Add(pip);
            return row;
        }

