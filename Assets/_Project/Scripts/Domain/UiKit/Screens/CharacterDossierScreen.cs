        private IEnumerable<UiNode> BuildSlot(EquipmentSlot slot)
        {
            string key = EquipmentSlots.DisplayName(slot).Replace(" ", "");
            var at = DossierLayout.SlotAt(slot);

            // No hairline for the centred pair -- HEAD sits directly above the
            // figure's head and SHOES directly below its feet, so adjacency
            // already says which body part they belong to. Width 0 is how
            // DossierLayout.LeaderAt says so; emitting it anyway would be a
            // zero-sized graphic, which A6 refuses and is right to.
            var leaderAt = DossierLayout.LeaderAt(slot, out float leaderWidth);
            if (leaderWidth > 0f)
            {
                yield return Ui.Solid($"DossierLeader{key}", "#C8B4DE2E",
                    new UiVec(leaderWidth, 1f), Place.At(leaderAt.X, leaderAt.Y)).AsDecor();
            }

            // 6px of inset, down from 12. The slot box cannot grow -- the
            // figure's slots sit 98 authored units apart and the box plus its
            // caption already spend 88 of that -- so the only room left for the
            // ITEM is the padding inside the box it already has.
            // ABOVE THE CAPTION BAND, not across it. The caption moved inside
            // the socket and the icon filled the whole socket, so an equipped
            // sword was drawn straight through the word naming its slot --
            // "WEA(sword)ON 1". The icon gets the socket minus that band.
            const float CaptionBand = 22f;
            float iconSize = DossierLayout.SlotSize - CaptionBand;
            var icon = Ui.Sprite($"DossierSlotIcon{key}", null,
                new UiVec(iconSize, iconSize),
                Place.At(0f, CaptionBand * 0.5f)).Inactive().AsDecor();

            var tick = Ui.Solid($"DossierSlotTick{key}", "#7F8EA3", new UiVec(11f, 11f),
                Place.At(-DossierLayout.SlotSize * 0.5f + 7f, DossierLayout.SlotSize * 0.5f - 7f))
                .Inactive().AsDecor();

            // ITEM-MODIFIER PLAN PHASE E: see BuildPack's identical comment
            // on why this is sized to the icon rather than bled past it.
            var riftGlow = Ui.Sprite($"DossierSlotRiftGlow{key}", "proc:ring_hairline",
                    new UiVec(iconSize, iconSize),
                    Place.At(0f, CaptionBand * 0.5f))
                .Inactive().AsDecor();

            // The blocked caption. A two-handed weapon must never leave the off
            // hand looking merely empty -- the player has to see WHY.
            var blocked = Ui.Label($"DossierSlotBlocked{key}", UiStrings.OverlayTwoHanded,
                new UiVec(DossierLayout.SlotSize - 8f, 26f), 9, TextDim, Place.At(0f, 0f))
                .Inactive().AsDecor();

            var cell = Ui.Button($"DossierSlot{key}", UiString.Runtime,
                    new UiVec(DossierLayout.SlotSize, DossierLayout.SlotSize), 1,
                    Place.At(at.X, at.Y))
                .NoChrome()
                .Hovers(1.05f)
                .AllowOverlap("a slot stands on the mannequin and its own leader line");
            cell.Children.Add(icon);
            cell.Children.Add(riftGlow);
            cell.Children.Add(tick);
            cell.Children.Add(blocked);

            // THE SOCKET'S OWN FRAME, which the handover specified and nothing
            // ever drew: SlotEmptyBorder and SlotBorder have sat in the token
            // table above, declared and referenced by nothing, since the screen
            // was written.
            //
            // Without it an unequipped slot renders as literally nothing -- the
            // loadout was a column of captions at the panel's edge with a
            // leader stub floating near the figure and empty space between them,
            // which is what "the silhouette still looks very weird" was about.
            // Growing the boxes did not help while they were invisible.
            //
            // Drawn at the empty weight for every slot. Swapping to SlotBorder
            // when something is worn needs the controller to hold four node refs
            // per slot, which is a bigger change than making the socket visible
            // at all -- so SlotBorder stays unused for now, and knowingly.
            foreach (var edge in Ui.Rim($"DossierSlot{key}",
                         new UiVec(DossierLayout.SlotSize, DossierLayout.SlotSize), SlotEmptyBorder))
            {
                cell.Children.Add(edge);
            }

            // INSIDE the socket, along its bottom edge.
            //
            // Under the box it spent vertical room the box needed; beside it,
            // once the boxes moved out to their files, the word ended up an
            // inch from the socket it named with nothing between them. Inside,
            // the socket and its word are one object and the files can sit
            // wherever the figure leaves room.
            var label = Ui.Label($"DossierSlotLabel{key}", UiString.Runtime,
                new UiVec(DossierLayout.SlotSize - 8f, 16f), 11, TextDim,
                Place.At(at.X, at.Y - DossierLayout.SlotSize * 0.5f + 11f)).AsDecor();

            SlotCells.Add(cell);
            SlotIcons.Add(icon);
            SlotRiftGlows.Add(riftGlow);
            SlotRarityTicks.Add(tick);
            SlotBlockedCaptions.Add(blocked);
            SlotLabels.Add(label);

            yield return cell;
            yield return label;
        }

        // ---- column C: the numbers ---------------------------------------------------

        private IEnumerable<UiNode> BuildColumnC()
        {
            float cx = DossierLayout.ColumnCCentreX;

            // WAS a plain decorative label. Now the opener for the
            // attributes panel (owner item: "dedicated attributes screen
            // showing stat effects") -- same rect, same text, so promoting
            // it costs the header row no new space. Same row+panel shape as
            // Pack/Spells/Skills/Track's own openers (DeclareColumnARows'
            // own header), just this one lives in column C instead of A
            // because that is where the thing it opens already is.
            var attributesRow = Ui.Button("DossierAttributesRow", UiStrings.OverlayAttributes,
                    new UiVec(160f, 20f), 10,
                    Place.At(cx - DossierLayout.ContentCWidth * 0.5f + 80f,
                             DossierLayout.ColumnCTop - 10f))
                .NoChrome();
            AttributesRow = attributesRow;
            yield return attributesRow;

            yield return Ui.Solid("DossierAttributesRule", Rule,
                new UiVec(DossierLayout.ContentCWidth, 1f),
                Place.At(cx, DossierLayout.ColumnCTop - 24f)).AsDecor();

            // HOW MANY POINTS ARE WAITING, on the same line as the section
            // label. Without it the "+" buttons are the only thing saying a
            // point exists, and they are 22px each in the corner of a cell --
            // easy to have and never notice, which is how levelling came to
            // hand out something nobody could see.
            var unspent = Ui.Label("DossierUnspentPoints", UiString.Runtime,
                new UiVec(180f, 20f), 11, Accent,
                Place.At(cx + DossierLayout.ContentCWidth * 0.5f - 90f,
                         DossierLayout.ColumnCTop - 10f));
            UnspentPoints = unspent;
            yield return unspent;

            // Six generic cells. Which attribute lands where is decided per
            // character at runtime -- the handover wants them highest-first so
            // the shape of the build reads off the first row.
            for (int i = 0; i < SheetStats.Abilities.Length; i++)
            {
                int row = i / 3;
                int column = i % 3;
                float x = DossierLayout.AttributeCellCentreX(column);
                float y = DossierLayout.AttributeCellCentreY(row);

                var value = Ui.Label($"DossierAttrValue{i}", UiString.Runtime, new UiVec(90f, 36f), 30, Text,
                    Place.At(0f, 10f)).AsDecor();
                var keyLabel = Ui.Label($"DossierAttrKey{i}", UiString.Runtime, new UiVec(90f, 16f), 10, TextDim,
                    Place.At(0f, -18f)).AsDecor();

                var cell = Ui.Button($"DossierAttrCell{i}", UiString.Runtime,
                        // MINUS 2, because cells tiled edge to edge share a
                        // boundary and the overlap check reads a shared edge as
                        // an overlap -- rightly, since the later sibling would
                        // take clicks along it.
                        new UiVec(DossierLayout.AttributeCellWidth - 2f, DossierLayout.AttributeCellHeight - 2f), 1,
                        Place.At(x, y))
                    .NoChrome();
                // The "+" that spends a point into this score. Inactive in the
                // tree: it appears only when there is a point to spend, and a
                // permanently visible one on a character with none reads as
                // broken.
                float halfWidth = (DossierLayout.AttributeCellWidth - 2f) * 0.5f;
                float halfHeight = (DossierLayout.AttributeCellHeight - 2f) * 0.5f;
                var plus = Ui.Button($"DossierAttrPlus{i}", UiStrings.DossierSpendPoint,
                        new UiVec(DossierLayout.AttributePlusSize, DossierLayout.AttributePlusSize), 14,
                        Place.At(halfWidth - DossierLayout.AttributePlusInset,
                                 halfHeight - DossierLayout.AttributePlusInset))
                    .NoChrome()
                    .Inactive();
                // The "-" that refunds a point out of this score. Mirrored off
                // the plus across the cell's centre, same size and inset, same
                // inactive-until-shown treatment -- but gated per cell rather
                // than globally, since a refund can only come out of a score
                // that has something invested in it (see PaintStatSpending).
                var minus = Ui.Button($"DossierAttrMinus{i}", UiStrings.DossierRefundPoint,
                        new UiVec(DossierLayout.AttributePlusSize, DossierLayout.AttributePlusSize), 14,
                        Place.At(-(halfWidth - DossierLayout.AttributePlusInset),
                                 halfHeight - DossierLayout.AttributePlusInset))
                    .NoChrome()
                    .Inactive();

                cell.Children.Add(value);
                cell.Children.Add(keyLabel);
                cell.Children.Add(plus);
                cell.Children.Add(minus);

