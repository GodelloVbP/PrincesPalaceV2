        public static CharacterDossierScreen Build()
        {
            var screen = new CharacterDossierScreen();

            // The stat list is generated from SheetStats, so it can outgrow its
            // column the moment somebody adds a row. Same guard, same reasoning
            // as the system menu's tab bar.
            int statCount = SheetStats.Derived.Length;
            if (!DossierLayout.StatListFits(statCount))
            {
                throw new System.InvalidOperationException(
                    $"The dossier has {statCount} stat rows but column C holds {DossierLayout.MaxStatRows()} " +
                    $"at {DossierLayout.StatRowHeight}px. Shorten the rows, lengthen the panel, or the list " +
                    "needs to scroll - it cannot simply be given another entry.");
            }

            var children = new List<UiNode>();

            // ITS OWN GROUND, restored -- the same flat #120a18 fill this pane
            // drew before 2f3ccd0's container, back again since the outer
            // Blue 2:1 frame that replaced it is gone (balance-bot item 2,
            // 2026-09-03). This pane opens over the hub and the fight, and a
            // transparent sheet lets a painted background read straight
            // through the numerals. The DossierVeil "light from above" wash
            // is NOT reinstated with it -- it was a hierarchy fix for a flat
            // field of equal-weight columns, and column A's own Blue 3:4 card
            // already gives this pane the hierarchy it needs.
            children.Add(Ui.Solid("DossierGround", Ground,
                    new UiVec(DossierLayout.Width, DossierLayout.Height), Place.At(0f, 0f))
                .AsDecor());

            children.Add(screen.BuildColumnAFrame());
            children.AddRange(screen.BuildColumnB());
            children.AddRange(screen.BuildColumnC());

            // The two column dividers, sized to the outer container's own
            // content extent (HalfHeight * 2f) rather than the raw 804-tall
            // frame -- Height would now run past the painted border.
            float dividerHeight = DossierLayout.HalfHeight * 2f - DossierLayout.PadY * 2f;
            children.Add(Ui.Solid("DossierDividerAB", Rule,
                new UiVec(1f, dividerHeight),
                Place.At(DossierLayout.DividerAtoB, 0f)).AsDecor());
            children.Add(Ui.Solid("DossierDividerBC", Rule,
                new UiVec(1f, dividerHeight),
                Place.At(DossierLayout.DividerBtoC, 0f)).AsDecor());

            // The pack covers column A entirely, so it is declared AFTER it.
            children.Add(screen.BuildPackPanel());

            // Same shape, one row later: covers column A too, and is
            // declared after the pack so the two never fight over which one
            // draws on top (only one is ever active at a time, per the
            // controller's own arm-one-panel-at-a-time rule).
            children.Add(screen.BuildSpellsPanel());

            // And the tooltip over everything.
            children.Add(screen.BuildTooltip());

            // NO OUTER FRAME (balance-bot item 2, 2026-09-03) -- the Blue 2:1
            // container 2f3ccd0 wrapped this pane in was "the big blue
            // container": a second frame around column A's own Blue 3:4
            // card, reading as one frame nested in another rather than one
            // clear card. Column A keeps its card; this pane goes back to a
            // bare panel the size of the content area, same as before that
            // commit and same as the flat ground it briefly replaced (no veil
            // reinstated either -- the system menu's own pane background
            // already grounds this, which is what let the veil be dropped
            // for the container's border in the first place).
            var pane = Ui.Panel("CharacterDossier", Place.At(0f, 0f),
                UiSize.Fixed(DossierLayout.Width, DossierLayout.Height), children.ToArray());

            screen.Root = pane;
            return screen;
        }

        // ---- column A: identity ---------------------------------------------------

        // GRAPHIC-LESS since 2026-09-07 (owner's call: every kit frame inside
        // the system menu read as ugly). Column A kept a Blue 3:4 Container
        // here until then; the RECT survives at the exact same size and place
        // -- DossierLayout.ColumnAFrameHeight still derives from the 3:4
        // aspect it was authored to fill, ColumnATop/ColumnABottom still
        // measure against it -- only the painted border and the separate
        // inset content panel are gone. The identity content (portrait, name,
        // pager, XP, nav rows) is a direct child of this one panel now, at
        // cx = 0 (column A's own centre, not the dossier's), the same
        // convention BuildPackPanel already uses for content that lives on a
        // panel placed at ColumnACentreX. CharacterDossierScreenTests.
        // ColumnAIdentityContentRidesInsideTheFrame pins that the identity
        // content still rides inside this one named parent, so moving or
        // hiding it cannot strand a label over the sky beside it.
        private UiNode BuildColumnAFrame()
        {
            return Ui.Panel("DossierColumnAFrame",
                Place.At(DossierLayout.ColumnACentreX, 0f),
                UiSize.Fixed(DossierLayout.ColumnAWidth, DossierLayout.ColumnAFrameHeight),
                BuildColumnA().ToArray());
        }

        private IEnumerable<UiNode> BuildColumnA()
        {
            const float cx = 0f;

            var portrait = Ui.Sprite("DossierPortrait", PortraitKey,
                    Place.At(cx, DossierLayout.PortraitCentreY),
                    UiSize.Fixed(DossierLayout.ContentAWidth, DossierLayout.PortraitHeight))
                .Coloured("#6640884D")
                .AsDecor();
            Portrait = portrait;
            yield return portrait;

            var name = Ui.Label("DossierName", UiString.Runtime,
                new UiVec(DossierLayout.ContentAWidth - 76f, 42f), 34, TextHi,
                Place.At(cx, DossierLayout.NameCentreY));
            CharacterName = name;
            yield return name;

            // The roster arrows the old sheet had. The handover does not show
            // them -- it draws one character -- but the game has five and no
            // other way to reach them from here, so dropping them would be a
            // capability regression dressed as a redesign.
            var pager = Ui.Pager(
                "DossierPrevCharacter",
                Place.At(cx - DossierLayout.ContentAWidth * 0.5f + 17f, DossierLayout.NameCentreY),
                "DossierNextCharacter",
                Place.At(cx + DossierLayout.ContentAWidth * 0.5f - 17f, DossierLayout.NameCentreY),
                new UiVec(34f, 34f), 18);
            PrevCharacterButton = pager.Prev;
            NextCharacterButton = pager.Next;
            yield return pager.Prev;
            yield return pager.Next;

            var sub = Ui.Label("DossierSubLine", UiString.Runtime,
                new UiVec(DossierLayout.ContentAWidth, 24f), 14, Accent,
                Place.At(cx, DossierLayout.SubLineCentreY));
            SubLine = sub;
            yield return sub;

            // XP: label, a 3px track with its fill, and what is left.
            yield return Ui.Label("DossierXpLabel", UiStrings.OverlayXp, new UiVec(30f, 16f), 10, TextDim,
                Place.At(cx - DossierLayout.ContentAWidth * 0.5f + 15f, DossierLayout.XpRowCentreY)).AsDecor();

            float trackWidth = DossierLayout.XpTrackWidth;
            float trackLeft = cx + DossierLayout.XpTrackLeft;
            yield return Ui.Solid("DossierXpTrack", "#C8B4DE24",
                new UiVec(trackWidth, 3f),
                Place.At(trackLeft + trackWidth * 0.5f, DossierLayout.XpRowCentreY)).AsDecor();

            var fill = Ui.Solid("DossierXpFill", Accent, new UiVec(trackWidth, 3f),
                    Place.At(trackLeft, DossierLayout.XpRowCentreY, new UiVec(0f, 0.5f)))
                .AsDecor();
            XpFill = fill;
            yield return fill;

            var left = Ui.Label("DossierXpRemaining", UiString.Runtime, new UiVec(70f, 16f), 11, TextDim,
                Place.At(cx + DossierLayout.ContentAWidth * 0.5f - 35f, DossierLayout.XpRowCentreY));
            XpRemaining = left;

            yield return left;

            // The two nav rows. BuildNavRow assigns its own refs -- an iterator
            // cannot carry `out` parameters, and threading them back through the
            // caller bought nothing.
            yield return BuildNavRow("Spells", UiStrings.DossierSpellsRow, DossierLayout.SpellsNavRowCentreY);
            yield return BuildNavRow("Track", UiStrings.TrackRow, DossierLayout.TrackNavRowCentreY);
            yield return BuildNavRow("Skills", UiStrings.OverlaySkills, DossierLayout.SkillsRowCentreY);
            yield return BuildNavRow("Pack", UiStrings.OverlayPack, DossierLayout.PackRowCentreY);
        }

        // LEFT AS THE HAIRLINE LIST THEY ARE (owner's HQ-kit instruction,
        // 2026-09-07, with the checked-and-declined exception the
        // instruction itself allows for). 380x56 rows are 6.79:1, nearest
        // Row6x1's 6:1 -- but the honest resize is 380x63.3, and stacking
        // four of those (NavRowHeight applied four times from
        // ColumnABottom) pushes the topmost row's (Spells) top edge to
        // roughly y=-10.1, thirteen pixels ABOVE the reward-track readout's
        // own bottom edge at roughly y=-23.4 (DossierLayout.TrackRowCentreY
        // minus half TrackRowHeight) -- a real overlap under the XP bar, not
        // a near miss, and one that does not depend on canvas aspect since
        // nothing in this column's arithmetic reads one. Growing the rows
        // would mean shrinking something above them (the portrait already
        // absorbed 165px of a prior repin, per DossierLayout.PortraitHeight's
        // own comment) rather than a free resize, so this is left as it was.
        private UiNode BuildNavRow(string key, UiString label, float centreY)
        {
            const float cx = 0f;

            var button = Ui.Button($"Dossier{key}Row", UiString.Runtime,
                    new UiVec(DossierLayout.ContentAWidth, DossierLayout.NavRowHeight), 1,
                    Place.At(cx, centreY))
                .NoChrome();

            button.Children.Add(Ui.Solid($"Dossier{key}RowRule", Rule,
                new UiVec(DossierLayout.ContentAWidth, 1f),
                Place.At(0f, DossierLayout.NavRowHeight * 0.5f - 0.5f)).AsDecor());

            // ...RowName, NOT ...RowLabel. UiEmitter names a button's own
            // caption "<button>Label", so a child called that collides with an
            // object the tree never declares and every lookup by name silently
            // takes the emitter's empty one -- AUDIT #39, caught here by the
            // check that finding added.
            button.Children.Add(Ui.Label($"Dossier{key}RowName", label,
                new UiVec(160f, 24f), 17, Text,
                Place.At(-DossierLayout.ContentAWidth * 0.5f + 82f, 0f)).AsDecor());

            // WIDER FOR THE TRACK. "LEVEL 6: +3% EXPERIENCE" does not fit the
            // 90px a count like "0 known" needs, and shrinking it to fit would
            // make the one sentence on this screen that names a reward the
            // smallest text on it.
            float countWidth = key == "Track" ? 210f : 90f;
            var countLabel = Ui.Label($"Dossier{key}RowCount", UiString.Runtime,
                new UiVec(countWidth, 20f), key == "Track" ? 11 : 12, TextDim,
                Place.At(DossierLayout.ContentAWidth * 0.5f - 6f - countWidth * 0.5f, 0f)).AsDecor();
            button.Children.Add(countLabel);

            var chev = Ui.Label($"Dossier{key}RowChevron", UiString.Runtime,
                new UiVec(20f, 24f), 16, Accent,
                Place.At(DossierLayout.ContentAWidth * 0.5f - 12f, 0f)).AsDecor();
            button.Children.Add(chev);

            // Assigned here rather than returned, so the two call sites stay
            // one line each.
            // The track row's COUNT LABEL is where "LEVEL 6: +3% EXPERIENCE"
            // now lives. It was a standalone line under the XP bar until this
            // screen existed -- two readouts of one fact, and UiAudit caught
            // them overlapping the moment the row arrived. The row is the
            // better home: it says what is next AND is the door to the rest.
            if (key == "Skills") { SkillsRow = button; SkillsCount = countLabel; }
            else if (key == "Track") { TrackRow = button; TrackNext = countLabel; }
            else if (key == "Spells") { SpellsRow = button; SpellsCount = countLabel; SpellsChevron = chev; }
            else { PackRow = button; PackChevron = chev; }

            return button;
        }

