        public static CharacterDossierScreen Build()
        {
            var screen = new CharacterDossierScreen();

            var sections = new List<UiNode>
            {
                screen.BuildLoadout(),
                screen.BuildAttributes(),
                screen.BuildSkills(),
                screen.BuildRewardTrack(),
            };

            // ALTERNATIVES, not a pile: one section shows at a time, so they
            // are exempt from each other and checked against everything else.
            Ui.Exclusive(sections);

            var detail = Ui.Panel("DossierDetail",
                Place.At(DossierLayout.DetailCentreX, DossierLayout.DetailCentreY),
                UiSize.Fixed(DossierLayout.DetailWidth, DossierLayout.DetailHeight),
                sections);

            var children = new List<UiNode>
            {
                screen.BuildStrip(),
                screen.BuildRail(),
                Ui.Solid("DossierRailRule", Rule, new UiVec(1f, DossierLayout.BodyHeight),
                    Place.At(DossierLayout.RailRuleX, DossierLayout.BodyCentreY)).AsDecor(),
                detail,
            };

            screen.Root = Ui.Panel("CharacterDossier", Place.At(0f, 0f),
                UiSize.Fixed(DossierLayout.Width, DossierLayout.Height), children);
            return screen;
        }

        private static UiNode Words(string name, UiString text, UiVec size, int fontSize, string colour,
                                    Place place, TypographyRole role, UiTextAlign align) =>
            Ui.Label(name, text, size, fontSize, colour, place)
                .Styled(role)
                .TextAligned(align)
                .AsDecor();

        // A focusable cell: the kit's default hover rim is its hover, the
        // focus marker is its focus, and nothing scales (plan C13).
        private static UiNode Cell(string name, UiVec size, Place place) =>
            Ui.Button(name, UiString.Runtime, size, 20, place)
                .NoChrome()
                .Styled(TypographyRole.Body);

        // The gold ring that marks a pending state's source (plan C13), built
        // as four edges under one panel the controller switches on.
        private static UiNode PendingRing(string name, UiVec size)
        {
            var ring = Ui.Panel(name, Place.At(0f, 0f), UiSize.Fixed(size.X, size.Y),
                Ui.Rim(name, size, PendingRim)).AsDecor().Inactive();
            return ring;
        }

        // ---- the strip -----------------------------------------------------------------

        private UiNode BuildStrip()
        {
            var children = new List<UiNode>();

            var prev = StripPager("DossierStripPrev", DossierLayout.PagerPrevX, out var prevGlyph);
            var next = StripPager("DossierStripNext", DossierLayout.PagerNextX, out var nextGlyph);
            StripPrev = prev;
            StripNext = next;
            StripPrevGlyph = prevGlyph;
            StripNextGlyph = nextGlyph;
            children.Add(prev);
            children.Add(next);

            for (int i = 0; i < DossierLayout.ChipCapacity; i++)
            {
                children.Add(BuildChip(i));
            }

            var divider = Ui.Solid("DossierStripDivider", Rule, new UiVec(1f, DossierLayout.ChipHeight),
                    Place.At(DossierLayout.DividerCentreX(3), 0f))
                .AsDecor()
                .Inactive();
            StripDivider = divider;
            children.Add(divider);

            return Ui.Panel("DossierStrip", Place.At(0f, DossierLayout.StripCentreY),
                UiSize.Fixed(DossierLayout.AreaWidth, DossierLayout.StripHeight), children);
        }

        // The LB and RB plates: the button the pad would press, drawn where
        // the mouse can press it. The letters follow the device (Q and E on
        // the keyboard).
        private static UiNode StripPager(string name, float x, out UiNode glyph)
        {
            var size = new UiVec(DossierLayout.PagerWidth, DossierLayout.PagerHeight);
            glyph = Words(name + "Glyph", UiString.Runtime, size, 22, Text, Place.At(0f, 0f),
                TypographyRole.Body, UiTextAlign.Centre);

            var button = Ui.Button(name, UiString.Runtime, size, 22, Place.At(x, 0f))
                .NoChrome()
                .Quiet()
                .Styled(TypographyRole.Body);
            button.Children.Add(Ui.Solid(name + "Fill", SocketFill, size, Place.At(0f, 0f)).AsDecor());
            foreach (var edge in Ui.Rim(name, size, SocketRim)) button.Children.Add(edge);
            button.Children.Add(glyph);
            return button;
        }

        private UiNode BuildChip(int index)
        {
            var size = new UiVec(DossierLayout.ChipWidth, DossierLayout.ChipHeight);

            var portrait = Ui.Sprite($"DossierChip{index}Portrait", PortraitKey,
                    new UiVec(DossierLayout.ChipPortraitSize, DossierLayout.ChipPortraitSize),
                    Place.At(DossierLayout.ChipPortraitX, 0f))
                .Coloured("#6640884D")
                .AsDecor();

            var name = Words($"DossierChip{index}Name", UiString.Runtime,
                    new UiVec(DossierLayout.ChipTextWidth, DossierLayout.ChipLineHeight), 20, Text,
                    Place.At(DossierLayout.ChipTextCentreX, DossierLayout.ChipNameY),
                    TypographyRole.Body, UiTextAlign.Left)
                .Truncated();

            var seat = Words($"DossierChip{index}Seat", UiString.Runtime,
                    new UiVec(DossierLayout.ChipTextWidth, DossierLayout.ChipLineHeight), 20, TextMuted,
                    Place.At(DossierLayout.ChipTextCentreX, DossierLayout.ChipSeatY),
                    TypographyRole.Body, UiTextAlign.Left)
                .Truncated();

            // Attention (plan C20) arrives in phase 5e; the slot is here so the
            // chip's layout does not move when it does.
            var pip = Ui.Sprite($"DossierChip{index}Pip", "proc:solid_circle",
                    new UiVec(DossierLayout.ChipPipSize, DossierLayout.ChipPipSize),
                    Place.At(DossierLayout.ChipPipX, DossierLayout.ChipPipY))
                .Coloured(Gold)
                .AsDecor()
                .Inactive();

            var selected = Ui.Panel($"DossierChip{index}Selected", Place.At(0f, 0f), UiSize.Fixed(size.X, size.Y),
                Ui.Rim($"DossierChip{index}Selected", size, FightHudPalette.BorderGold)).AsDecor().Inactive();

            var chip = Ui.Button($"DossierChip{index}", UiString.Runtime, size, 20,
                    Place.At(DossierLayout.ChipCentreX(index, -1), 0f))
                .NoChrome()
                .Quiet()
                .Styled(TypographyRole.Body);
            chip.Children.Add(Ui.Solid($"DossierChip{index}Fill", SocketFill, size, Place.At(0f, 0f)).AsDecor());
            foreach (var edge in Ui.Rim($"DossierChip{index}", size, SocketRim)) chip.Children.Add(edge);
            chip.Children.Add(selected);
            chip.Children.Add(portrait);
            chip.Children.Add(name);
            chip.Children.Add(seat);
            chip.Children.Add(pip);

            Chips.Add(chip);
            ChipPortraits.Add(portrait);
            ChipNames.Add(name);
            ChipSeats.Add(seat);
            ChipPips.Add(pip);
            ChipSelectedRims.Add(selected);
            return chip;
        }

