        private UiNode BuildLoadout()
        {
            var children = new List<UiNode>();

            // The figure first, so the slots draw over it: a fill that barely
            // registers and a traced line that carries the reading.
            var figureSize = new UiVec(DossierLayout.FigureWidth, DossierLayout.FigureHeight);
            var figureAt = DossierLayout.FigureCentre;
            children.Add(Ui.Sprite("DossierMannequinFill", MannequinKey, figureSize, Place.At(figureAt.X, figureAt.Y))
                .Coloured("#B9A2D60E").AsDecor());
            children.Add(Ui.Sprite("DossierMannequinOutline", MannequinOutlineKey, figureSize,
                    Place.At(figureAt.X, figureAt.Y))
                .Coloured("#EDE4FF5C").AsDecor());

            foreach (var slot in EquipmentSlots.All)
            {
                children.AddRange(BuildGearSlot(slot));
            }

            var heading = Words("DossierBooksHeading", UiStrings.LoadoutBooksHeading,
                new UiVec(DossierLayout.SlotsWidth, DossierLayout.BooksHeadingHeight), 24, Gold,
                Place.At(DossierLayout.DX(DossierLayout.SlotsLeft + DossierLayout.SlotsWidth * 0.5f),
                    DossierLayout.BooksHeadingCentreY),
                TypographyRole.FunctionalHeading, UiTextAlign.Left);
            BooksHeading = heading;
            children.Add(heading);

            for (int i = 0; i < SpellBooks.MaxSpellSlots; i++)
            {
                children.AddRange(BuildBookSlot(i));
            }

            // One sentence in place of the whole book row for a character whose
            // pool refuses books: the answer is "never", not "not yet", so no
            // greyed slots stand there inviting a press.
            var noBooks = Words("DossierNoBooksLine", UiStrings.DossierNoSpellBooks,
                    new UiVec(DossierLayout.SlotsWidth, DossierLayout.NoBooksHeight), 20, TextSecondary,
                    Place.At(DossierLayout.NoBooksCentre.X, DossierLayout.NoBooksCentre.Y),
                    TypographyRole.Body, UiTextAlign.TopLeft)
                .Inactive();
            NoBooksLine = noBooks;
            children.Add(noBooks);

            BuildPack(children);
            BuildCompare(children);

            var section = Section("DossierLoadout", children);
            LoadoutSection = section;
            return section;
        }

        private IEnumerable<UiNode> BuildGearSlot(EquipmentSlot slot)
        {
            string key = EquipmentSlots.DisplayName(slot).Replace(" ", "");
            var at = DossierLayout.GearCentre(slot);
            var size = new UiVec(DossierLayout.SlotSize, DossierLayout.SlotSize);
            float iconSize = DossierLayout.SlotSize - 16f;

            var icon = Ui.Sprite($"DossierSlotIcon{key}", null, new UiVec(iconSize, iconSize), Place.At(0f, 0f))
                .Inactive().AsDecor();
            var glow = Ui.Sprite($"DossierSlotRiftGlow{key}", "proc:ring_hairline", new UiVec(iconSize, iconSize),
                    Place.At(0f, 0f))
                .Inactive().AsDecor();
            var tick = Ui.Solid($"DossierSlotTick{key}", "#7F8EA3", new UiVec(12f, 12f),
                    Place.At(-size.X * 0.5f + 9f, size.Y * 0.5f - 9f))
                .Inactive().AsDecor();
            var armed = PendingRing($"DossierSlotArmed{key}", size);

            var cell = Cell($"DossierSlot{key}", size, Place.At(at.X, at.Y));
            cell.Children.Add(Ui.Solid($"DossierSlot{key}Fill", SocketFill, size, Place.At(0f, 0f)).AsDecor());
            foreach (var edge in Ui.Rim($"DossierSlot{key}", size, SocketRim)) cell.Children.Add(edge);
            cell.Children.Add(icon);
            cell.Children.Add(glow);
            cell.Children.Add(tick);
            cell.Children.Add(armed);

            var captionAt = DossierLayout.GearCaptionCentre(slot);
            var caption = Words($"DossierSlotCaption{key}", UiString.Runtime,
                    new UiVec(DossierLayout.SlotCaptionWidth, DossierLayout.SlotCaptionHeight), 20, TextMuted,
                    Place.At(captionAt.X, captionAt.Y), TypographyRole.Body, UiTextAlign.Centre)
                .Truncated();

            SlotCells.Add(cell);
            SlotIcons.Add(icon);
            SlotRiftGlows.Add(glow);
            SlotRarityTicks.Add(tick);
            SlotArmedRims.Add(armed);
            SlotCaptions.Add(caption);

            yield return cell;
            yield return caption;
        }

