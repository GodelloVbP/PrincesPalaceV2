    // A portrait strip on top, a rail down the left, and a detail area showing
    // the rail's selected section: LOADOUT, ATTRIBUTES, SKILLS or the REWARD
    // TRACK. Nothing opens over anything -- every section is a panel the size
    // of the detail area, exactly one shown at a time, and the rail stays in
    // view whichever it is. The reward track is its own screen
    // (RewardTrackScreen), built here into the detail area.
    //
    // Type roles throughout (plan C14): FunctionalHeading for caps headings and
    // the rail's section names, Body for everything a player reads as text or
    // as a number. Not TacticalData: its material tints text violet, which
    // would turn a gain's green and a rarity's colour lilac (the RUN pane made
