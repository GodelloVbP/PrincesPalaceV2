        private void BuildPack(List<UiNode> children)
        {
            for (int i = 0; i < LoadoutPack.Filters.Length; i++)
            {
                var size = new UiVec(DossierLayout.FilterWidth, DossierLayout.FilterHeight);

                var caption = Words($"DossierFilter{i}Caption", LoadoutPack.Label(LoadoutPack.Filters[i]),
                    new UiVec(size.X, 30f), 20, Text, Place.At(0f, 2f),
                    TypographyRole.Body, UiTextAlign.Centre);

                // The live filter's underline, the tab bar's own marker.
                var marker = Ui.Solid($"DossierFilter{i}Marker", Gold, new UiVec(size.X - 16f, 3f),
                        Place.At(0f, -size.Y * 0.5f + 3f))
                    .AsDecor()
                    .Inactive();

                var chip = Ui.Button($"DossierFilter{i}", UiString.Runtime, size, 20,
                        Place.At(DossierLayout.FilterCentreX(i), DossierLayout.FilterCentreY))
                    .NoChrome()
                    .Quiet()
                    .Styled(TypographyRole.Body);
                foreach (var edge in Ui.Rim($"DossierFilter{i}", size, SocketRim)) chip.Children.Add(edge);
                chip.Children.Add(caption);
                chip.Children.Add(marker);

                FilterChips.Add(chip);
                FilterMarkers.Add(marker);
                children.Add(chip);
            }

            for (int i = 0; i < DossierLayout.PackVisibleCells; i++)
            {
                var at = DossierLayout.PackCellCentre(i);
                var size = new UiVec(DossierLayout.PackCell, DossierLayout.PackCell);
                var iconSize = new UiVec(DossierLayout.PackIconSize, DossierLayout.PackIconSize);

                var icon = Ui.Sprite($"DossierPackIcon{i}", null, iconSize, Place.At(0f, 4f)).Inactive().AsDecor();
                var glow = Ui.Sprite($"DossierPackRiftGlow{i}", "proc:ring_hairline",
                        new UiVec(DossierLayout.PackIconSize + 12f, DossierLayout.PackIconSize + 12f), Place.At(0f, 4f))
                    .Inactive().AsDecor();
                var tick = Ui.Solid($"DossierPackTick{i}", "#7F8EA3", new UiVec(12f, 12f),
                        Place.At(-size.X * 0.5f + 10f, size.Y * 0.5f - 10f))
                    .Inactive().AsDecor();
