using System.Collections.Generic;
using PrincesPalace.Domain.Content;
using PrincesPalace.Domain.Stats;
using TMPro;
using UnityEngine;

namespace PrincesPalace
{
    // Answers the two TMP asset lookups a rich-text tag can make and TMP would
    // otherwise miss: <font="..."> (grade letters, bold description runs) and
    // <sprite="..."> (description icons).
    //
    // WHY A RUNTIME FONT. TMP resolves a <font> tag from its own cache of
    // fonts already on screen, then from OnFontAssetRequest, then from
    // Resources/"Fonts & Materials"/. The generated SDF fonts live in
    // _Project/Fonts, outside Resources, and are only in the cache on a screen
    // that happens to show a label using one -- so leaning on the cache would
    // make a tag render or not depending on what else is visible, and TMP
    // prints an unresolved tag as literal text. The TTFs already ship under
    // Resources/Fonts, so each named font here is built once, dynamically,
    // from its TTF on first request. Dynamic and never saved: its atlas is
    // filled at runtime and nothing is written to disk, so there is no
    // glyph-table churn in git (AUDIT #47).
    //
    // Each font is named after the tag it answers, so TMP's cache keys it
    // under the same hash the tag carries and later lookups never reach this
    // hook.
    //
    // WHY A SPRITE HOOK. The icon asset sits under Resources/Icons, not TMP's
    // default "Sprite Assets/" folder, and a <sprite> tag TMP cannot resolve
    // is printed as text as well. The asset is only handed out when it holds
    // every icon DescriptionMarkup.Icons names, so a stale asset degrades the
    // whole set to words (DescriptionRenderer) instead of drawing some icons
    // and printing the rest.
    public static class TmpAssetResolver
    {
        // The TTF each answerable font name is built from.
        private static readonly Dictionary<string, string> FontSources = new Dictionary<string, string>
        {
            { ScalingGrades.DisplayFontName, "Fonts/SourceSans3/SourceSans3-SemiBold" },
            { DescriptionMarkup.BoldFontName, "Fonts/SourceSans3/SourceSans3-Bold" },
        };

        // Resources-relative, no extension. Generated by
        // TmpBootstrap.GenerateDescriptionIcons.
        public const string IconSpriteAssetPath = "Icons/DescriptionIcons/DescriptionIcons";

        private static readonly Dictionary<string, TMP_FontAsset> Fonts = new Dictionary<string, TMP_FontAsset>();
        private static readonly HashSet<string> FontsFailed = new HashSet<string>();
        private static TMP_SpriteAsset _icons;
        private static bool _iconsFailed;

#if UNITY_EDITOR
        // Edit-time rendering (scene previews, EditMode captures) resolves
        // the tags too, not only a play session.
        [UnityEditor.InitializeOnLoadMethod]
#endif
        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
        public static void Register()
        {
            // -= first: with domain reload off, a second play session would
            // otherwise subscribe twice. Harmless, but not a thing to leave.
            TMP_Text.OnFontAssetRequest -= ResolveFont;
            TMP_Text.OnFontAssetRequest += ResolveFont;
            TMP_Text.OnSpriteAssetRequest -= ResolveSprites;
            TMP_Text.OnSpriteAssetRequest += ResolveSprites;
        }

        // Forgets every asset and failure, so the next lookup builds again.
        public static void Reset()
        {
            Fonts.Clear();
            FontsFailed.Clear();
            _icons = null;
            _iconsFailed = false;
        }

        public static TMP_FontAsset ResolveFont(int hashCode, string name) => Font(name);

        public static TMP_SpriteAsset ResolveSprites(int hashCode, string name) =>
            name == DescriptionMarkup.IconSpriteAssetName ? IconSprites() : null;

        // The font a tag of this name draws with; null when the name is not
        // one this answers or its TTF cannot be built (warned once).
        public static TMP_FontAsset Font(string name)
        {
            if (name == null || !FontSources.TryGetValue(name, out string ttf)) return null;
            if (Fonts.TryGetValue(name, out TMP_FontAsset cached) && cached != null) return cached;
            if (FontsFailed.Contains(name)) return null;

            var source = Resources.Load<Font>(ttf);
            if (source == null)
            {
                // Graceful degradation: the caller falls back to plain text
                // (bold) or TMP prints the tag (grades), and this warns once
                // rather than every frame.
                FontsFailed.Add(name);
                Debug.LogWarning($"[TmpAssetResolver] No font at Resources/{ttf}; '{name}' cannot be drawn.");
                return null;
            }

            var built = TMP_FontAsset.CreateFontAsset(source);
            if (built == null)
            {
                FontsFailed.Add(name);
                Debug.LogWarning($"[TmpAssetResolver] Could not build a font asset from Resources/{ttf}.");
                return null;
            }

            // Every identity TMP keys a cache on is derived from the tag name,
            // material included: two runtime fonts sharing a material name
            // make TMP's material cache throw on the second one it meets.
            built.name = name;
            built.hashCode = TMP_TextUtilities.GetHashCode(name);
            built.material.name = name + " Material";
            built.materialHashCode = TMP_TextUtilities.GetSimpleHashCode(built.material.name);
            built.hideFlags = HideFlags.DontSave;
            Fonts[name] = built;
            return built;
        }

        // The icon sprite asset, or null when it is missing or lacks an icon
        // the registry names.
        public static TMP_SpriteAsset IconSprites()
        {
            if (_icons != null) return _icons;
            if (_iconsFailed) return null;

            var loaded = Resources.Load<TMP_SpriteAsset>(IconSpriteAssetPath);
            if (loaded == null)
            {
                _iconsFailed = true;
                Debug.LogWarning($"[TmpAssetResolver] No sprite asset at Resources/{IconSpriteAssetPath}; description icons render as words. Run Prince's Palace/Generate Description Icons.");
                return null;
            }

            foreach (DescriptionMarkup.Icon icon in DescriptionMarkup.Icons)
            {
                if (loaded.GetSpriteIndexFromName(icon.SpriteName) < 0)
                {
                    _iconsFailed = true;
                    Debug.LogWarning($"[TmpAssetResolver] Sprite asset lacks '{icon.SpriteName}'; description icons render as words. Run Prince's Palace/Generate Description Icons.");
                    return null;
                }
            }

            _icons = loaded;
            return _icons;
        }
    }
}
