using System;
using System.IO;
using UnityEditor;
using UnityEngine;

// Bakes the shapes a flat uGUI Image cannot draw into COMMITTED PNG assets.
//
// v1 generated these at runtime and assigned them from a component marked
// [ExecuteAlways], which meant the Edit Mode scene build assigned a sprite that
// was not an asset. Unity's response to that is to serialise the texture INTO
// the scene: measured on v2's main menu, 104 scene-local sprite references and
// an embedded Texture2D, accounting for most of a 624 KB scene file.
//
// It worked, but everything about it is bad: the texture is undiffable, it is
// duplicated once per scene that uses it, it cannot be inspected or replaced,
// and it makes a text-format scene file mostly binary noise.
//
// Baked PNGs are ordinary assets. One GUID, referenced by every scene, visible
// in a diff, and the same rule as everything else here: generated by a tool you
// can re-run, never hand-authored.
public static class ProceduralSpriteBaker
{
    public const string GeneratedDir = "Assets/_Project/Art/Generated";
    private const int Size = 128;

    [MenuItem("Prince's Palace/Bake Procedural Sprites")]
    public static void BakeAll()
    {
        Directory.CreateDirectory(GeneratedDir);

        // White at the centre fading smoothly to fully transparent at the edge.
        // Tinted through Image.color at every use site, which is why one asset
        // serves stars, lanterns, window bloom, motes and mist alike.
        Bake("radial_glow", dist => 1f - Smoothstep(Mathf.Clamp01(dist)));

        // A flat disc with a thin antialiased edge - a coin, an orb, anything
        // that must not render as a square.
        Bake("solid_circle", dist => 1f - Mathf.Clamp01((dist - 0.92f) / 0.08f));

        // A soft annulus: the fight stage's ground contact ring. Hollow, so an
        // actor reads as STANDING inside a mark on the floor rather than on top
        // of a painted disc -- and soft on both edges, because a hard ring at
        // this size reads as a drawn circle rather than as light on the ground.
        Bake("ring_outline", dist =>
        {
            const float centre = 0.72f;
            const float halfWidth = 0.20f;
            float offset = Mathf.Abs(Mathf.Clamp01(dist) - centre);
            return 1f - Smoothstep(Mathf.Clamp01(offset / halfWidth));
        });

        BakeRarityBurst();
        BakeBar();
        BakeScrim();

        AssetDatabase.SaveAssets();
        Debug.Log("BUILD-COMPLETE: ProceduralSpriteBaker");
    }

    // The glow that spins behind an offered item, tinted per rarity.
    //
    // GENERATED rather than painted, and here that is the better tool rather
    // than a placeholder standing in for one. The brief asks for three things
    // at once: rays that feather with no hard edge anywhere, a fade to nothing
    // WELL INSIDE the canvas so rotation cannot clip a ray at the diagonals,
    // and radial symmetry good enough that a spin does not wobble. A diffusion
    // model holds those by luck; arithmetic holds them by construction.
    //
    // White, so RarityColors tints one asset six ways.
    private static void BakeRarityBurst()
    {
        const int Rays = 29;              // prime, so no ray sits opposite another
        const float CoreRadius = 0.13f;   // the diffuse bloom in the middle
        const float FadeBy = 0.78f;       // gone by here, clear of every corner

        // Deterministic from the index. The baker must produce the same bytes
        // every run or WritePng's compare-before-write is defeated and every
        // build churns the file.
        var angle = new float[Rays];
        var width = new float[Rays];
        var reach = new float[Rays];

        for (int i = 0; i < Rays; i++)
        {
            // Evenly spaced then nudged, so the spacing reads as light rather
            // than as a cog.
            angle[i] = i / (float)Rays * Mathf.PI * 2f + Mathf.Sin(i * 12.9898f) * 0.06f;

            // Alternating thick and thin is what makes a burst read as light
            // instead of as a star polygon.
            width[i] = Mathf.Lerp(0.020f, 0.055f, Frac(i * 0.7548f));

            // UNEVEN LENGTHS. With every ray the same, a spin has nothing to
            // announce itself with and the whole thing looks static.
            reach[i] = Mathf.Lerp(0.42f, FadeBy, Frac(i * 0.3247f));
        }

        BakeGlow("rarity_burst", 1024, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);
            if (radius >= FadeBy) return 0f;

            float theta = Mathf.Atan2(ny, nx);

            // The core: a bloom with no edge of its own.
            float value = Mathf.Exp(-(radius * radius) / (CoreRadius * CoreRadius)) * 0.9f;

            for (int i = 0; i < Rays; i++)
            {
                float delta = Mathf.Abs(Mathf.DeltaAngle(theta * Mathf.Rad2Deg, angle[i] * Mathf.Rad2Deg))
                              * Mathf.Deg2Rad;

                // Gaussian across the ray, so it has no sides.
                float across = Mathf.Exp(-(delta * delta) / (width[i] * width[i]));
                if (across < 0.004f) continue;

                // And squared along it, so the tip dissolves rather than stops.
                float along = Mathf.Clamp01(1f - radius / reach[i]);
                value += across * along * along * 0.85f;
            }

            return Mathf.Clamp01(value);
        });
    }

    private static float Frac(float value) => value - Mathf.Floor(value);

    // The experience bar: a recessed channel and the light that fills it.
    //
    // UNIFORM ALONG X, both of them, and that is the whole design decision.
    // The fill is stretched to whatever fraction of the track has been earned,
    // so anything that varies horizontally -- a rounded cap, a highlight at one
    // end -- distorts as the bar grows and, worse, distorts DIFFERENTLY every
    // frame while it animates. All the shaping is vertical; the ends are square
    // and the track's own art supplies the enclosure.
    private static void BakeBar()
    {
        // The channel. Dark, with the light caught along its top lip so it
        // reads as cut into the panel rather than drawn on top of it.
        //
        // The body used to run 0.10..0.22, which is nearly black BEFORE the
        // Reckoning multiplies it by a dark violet tint -- the two darknesses
        // compounded to roughly #08060E and the bar read as a hole punched in
        // the panel rather than as a groove cut into it. Raised so the tint has
        // something to colour: the shading still does the recessing, but the
        // result stays recognisably a surface.
        BakeGradient("bar_track", 64, y =>
        {
            // Light bouncing off the floor of the groove, and the highlight
            // caught on its top lip. Keeping BOTH is what stops a raised level
            // reading as a flat plate: bright, dip, bright is a section through
            // a channel, and a single ramp is not.
            float floorBounce = Mathf.Clamp01(1f - y / 0.22f);
            float lip = Mathf.Exp(-Mathf.Pow((y - 0.94f) / 0.05f, 2f));

            float value = Mathf.Lerp(0.30f, 0.46f, y) + floorBounce * 0.10f;
            return (Mathf.Clamp01(value + lip * 0.42f), 1f);
        });

        // The fill. White so it can be tinted twice from one asset -- once for
        // what was already earned and once, brighter, for what this fight paid.
        BakeGradient("bar_fill", 64, y =>
        {
            // Brightest just under the top edge, falling away downward: a bar
            // lit from above rather than a flat block of colour.
            //
            // The old numbers said bloom and drew a flat white strip. body ran
            // 0.55..0.95 and the bloom added up to 0.55 on top, so everything
            // above y 0.45 clamped to 1 -- five eighths of the bar was one
            // saturated value and the gradient was invisible. A bloom is a
            // bright CORE against something less bright; without the contrast
            // there is nothing to read as light.
            //
            // Lowered and narrowed so the core saturates over roughly a fifth
            // of the height and falls off on both sides of it.
            float bloom = Mathf.Exp(-Mathf.Pow((y - 0.80f) / 0.26f, 2f));
            float body = Mathf.Lerp(0.34f, 0.62f, y);

            // Softened at both edges so it never shows a hard line against the
            // channel it sits in -- and widened with the channel, since a
            // lighter track shows a hard fill edge that a near-black one hid.
            float edge = Mathf.Clamp01(Mathf.Min(y, 1f - y) / 0.10f);

            return (Mathf.Clamp01(body + bloom * 0.62f), edge);
        });
    }

    // The stage scrim: two of its three layers. The third is `radial_glow`,
    // already baked above and simply tinted dark -- a knock-down and a bloom
    // are the same shape, and only the colour differs.
    //
    // BOTH BAKED WHITE, with all the shaping in ALPHA. The scrim's colour is a
    // layout decision and belongs in the screen tree where it can be read next
    // to the palette it has to sit against; baking a dark pixel here would put
    // half the decision in an Editor script and make the tint a multiplier on
    // a number nobody can see.
    private static void BakeScrim()
    {
        // A band across the actor rows. Soft at BOTH edges over a wide
        // falloff: a scrim whose own boundary is visible has become a shape on
        // the screen, which is the one thing it must never be. 0.30 either side
        // leaves a flat 40% core doing the actual separating.
        BakeGradient("scrim_band", 128, y =>
        {
            float edge = Mathf.Clamp01(Mathf.Min(y, 1f - y) / 0.30f);
            return (1f, Smoothstep(edge));
        });

        // Weighted to the bottom of the screen, under the command columns.
        // Squared rather than linear so it stays out of the way through the
        // middle of the frame and only bites where the HUD actually is --
        // a linear ramp put visible grey halfway up the backdrop.
        BakeGradient("scrim_floor", 128, y =>
        {
            float down = Mathf.Clamp01(1f - y);
            return (1f, Smoothstep(down * down));
        });
    }

    // A bar-shaped sprite that varies only with height. `shade` returns
    // (brightness, alpha) for a normalised y, 0 at the bottom.
    private static void BakeGradient(string name, int height, Func<float, (float value, float alpha)> shade)
    {
        const int Width = 16;   // uniform across, so this only has to be wide
                                // enough to survive filtering
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(Width, height, TextureFormat.RGBA32, false);
        var pixels = new Color32[Width * height];

        for (int y = 0; y < height; y++)
        {
            var (value, alpha) = shade((y + 0.5f) / height);
            byte channel = (byte)Mathf.RoundToInt(Mathf.Clamp01(value) * 255f);
            byte a = (byte)Mathf.RoundToInt(Mathf.Clamp01(alpha) * 255f);

            for (int x = 0; x < Width; x++)
            {
                pixels[y * Width + x] = new Color32(channel, channel, channel, a);
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    // White pixels whose ALPHA is the intensity. No rim and no signed
    // distance: a glow is a field, not a shape with an edge.
    private static void BakeGlow(string name, int size, Func<float, float, float> intensityAt)
    {
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
        var pixels = new Color32[size * size];

        for (int y = 0; y < size; y++)
        {
            for (int x = 0; x < size; x++)
            {
                float nx = (x + 0.5f) / size * 2f - 1f;
                float ny = (y + 0.5f) / size * 2f - 1f;

                float alpha = Mathf.Clamp01(intensityAt(nx, ny));
                pixels[y * size + x] = new Color32(255, 255, 255, (byte)Mathf.RoundToInt(alpha * 255f));
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    private static float Smoothstep(float x) => x * x * (3f - 2f * x);

    // A radially symmetric shape: alpha as a function of distance from centre,
    // white throughout so every use site can tint it.
    private static void Bake(string name, Func<float, float> alphaAtDistance)
    {
        var texture = new Texture2D(Size, Size, TextureFormat.RGBA32, false);
        var pixels = new Color32[Size * Size];

        for (int y = 0; y < Size; y++)
        {
            for (int x = 0; x < Size; x++)
            {
                float nx = (x + 0.5f) / Size * 2f - 1f;
                float ny = (y + 0.5f) / Size * 2f - 1f;
                float alpha = Mathf.Clamp01(alphaAtDistance(Mathf.Sqrt(nx * nx + ny * ny)));
                pixels[y * Size + x] = new Color32(255, 255, 255, (byte)Mathf.RoundToInt(alpha * 255f));
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng($"{GeneratedDir}/{name}.png", texture);
    }

    // Encode, compare, write, import. One place that knows the importer
    // settings a Sprite needs.
    private static void WritePng(string path, Texture2D texture)
    {
        var png = texture.EncodeToPNG();
        UnityEngine.Object.DestroyImmediate(texture);

        // Byte-compare before writing: an unchanged PNG must not be rewritten,
        // or every build churns the file and every diff is noise.
        if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(png))
        {
            return;
        }

        File.WriteAllBytes(path, png);
        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);

        // Without Sprite + alphaIsTransparency, LoadAssetAtPath<Sprite> returns
        // null with no error anywhere - the failure that shipped a spell playing
        // nothing for weeks in v1.
        var importer = AssetImporter.GetAtPath(path) as TextureImporter;
        if (importer != null)
        {
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.alphaIsTransparency = true;
            importer.mipmapEnabled = false;
            importer.SaveAndReimport();
        }

        Debug.Log($"[ProceduralSpriteBaker] baked {path}");
    }
}
