using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

// Bakes the shapes a flat uGUI Image cannot draw into COMMITTED PNG assets.
//
// v1 generated these at runtime and assigned them from a component marked
// [ExecuteAlways], which meant the Edit Mode scene build assigned a sprite that
// was not an asset. Unity's response to that is to serialise the texture INTO
// the scene: measured on v2's main menu, 104 scene-local sprite references and
// an embedded Texture2D, accounting for most of a 624 KB scene file.
//
// It worked, but everything about it is bad: the texture is undiffable, it is
// duplicated once per scene that uses it, it cannot be inspected or replaced,
// and it makes a text-format scene file mostly binary noise.
//
// Baked PNGs are ordinary assets. One GUID, referenced by every scene, visible
// in a diff, and the same rule as everything else here: generated by a tool you
// can re-run, never hand-authored.
public static class ProceduralSpriteBaker
{
    public const string GeneratedDir = "Assets/_Project/Art/Generated";
    private const int Size = 128;

    [MenuItem("Prince's Palace/Bake Procedural Sprites")]
    public static void BakeAll()
    {
        Directory.CreateDirectory(GeneratedDir);

        // White at the centre fading smoothly to fully transparent at the edge.
        // Tinted through Image.color at every use site, which is why one asset
        // serves stars, lanterns, window bloom, motes and mist alike.
        Bake("radial_glow", dist => 1f - Smoothstep(Mathf.Clamp01(dist)));

        // The exact inverse of radial_glow -- transparent at the centre,
        // opaque toward the edge. The low-HP vignette's own shape: attention
        // pulled to the FRAME closing in, not to a glow at a point inside it.
        Bake("vignette", dist => Smoothstep(Mathf.Clamp01(dist)));

        // A flat disc with a thin antialiased edge - a coin, an orb, anything
        // that must not render as a square.
        Bake("solid_circle", dist => 1f - Mathf.Clamp01((dist - 0.92f) / 0.08f));

        // A soft annulus: the fight stage's ground contact ring. Hollow, so an
        // actor reads as STANDING inside a mark on the floor rather than on top
        // of a painted disc -- and soft on both edges, because a hard ring at
        // this size reads as a drawn circle rather than as light on the ground.
        Bake("ring_outline", dist =>
        {
            const float centre = 0.72f;
            const float halfWidth = 0.20f;
            float offset = Mathf.Abs(Mathf.Clamp01(dist) - centre);
            return 1f - Smoothstep(Mathf.Clamp01(offset / halfWidth));
        });

        // The talent tree's edge kit. Soft along its SHORT axis and uniform
        // along its long one, so a quad stretched between two orbs fades at
        // its sides instead of ending on a hard 10px band -- which is what
        // makes an edge read as a lit crack rather than as a drawn rectangle.
        //
        // The same falloff ProceduralSprites.SoftEdgeStripe builds at runtime,
        // committed here because the emitter needs a real asset with a GUID.
        BakeGradient("soft_edge_stripe", 64,
            ny => (1f, 1f - Smoothstep(Mathf.Abs(ny * 2f - 1f))));

        BakeRarityBurst();
        BakeBar();
        BakeScrim();
        BakeEmber();
        BakeConstellation();

        AssetDatabase.SaveAssets();
        Debug.Log("BUILD-COMPLETE: ProceduralSpriteBaker");
    }

    // The glow that spins behind an offered item, tinted per rarity.
    //
    // GENERATED rather than painted, and here that is the better tool rather
    // than a placeholder standing in for one. The brief asks for three things
    // at once: rays that feather with no hard edge anywhere, a fade to nothing
    // WELL INSIDE the canvas so rotation cannot clip a ray at the diagonals,
    // and radial symmetry good enough that a spin does not wobble. A diffusion
    // model holds those by luck; arithmetic holds them by construction.
    //
    // White, so RarityColors tints one asset six ways.
    private static void BakeRarityBurst()
    {
        const int Rays = 29;              // prime, so no ray sits opposite another
        const float CoreRadius = 0.13f;   // the diffuse bloom in the middle
        const float FadeBy = 0.78f;       // gone by here, clear of every corner

        // Deterministic from the index. The baker must produce the same bytes
        // every run or WritePng's compare-before-write is defeated and every
        // build churns the file.
        var angle = new float[Rays];
        var width = new float[Rays];
        var reach = new float[Rays];

        for (int i = 0; i < Rays; i++)
        {
            // Evenly spaced then nudged, so the spacing reads as light rather
            // than as a cog.
            angle[i] = i / (float)Rays * Mathf.PI * 2f + Mathf.Sin(i * 12.9898f) * 0.06f;

            // Alternating thick and thin is what makes a burst read as light
            // instead of as a star polygon.
            width[i] = Mathf.Lerp(0.020f, 0.055f, Frac(i * 0.7548f));

            // UNEVEN LENGTHS. With every ray the same, a spin has nothing to
            // announce itself with and the whole thing looks static.
            reach[i] = Mathf.Lerp(0.42f, FadeBy, Frac(i * 0.3247f));
        }

        BakeTrackMarks();

        BakeGlow("rarity_burst", 1024, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);
            if (radius >= FadeBy) return 0f;

            float theta = Mathf.Atan2(ny, nx);

            // The core: a bloom with no edge of its own.
            float value = Mathf.Exp(-(radius * radius) / (CoreRadius * CoreRadius)) * 0.9f;

            for (int i = 0; i < Rays; i++)
            {
                float delta = Mathf.Abs(Mathf.DeltaAngle(theta * Mathf.Rad2Deg, angle[i] * Mathf.Rad2Deg))
                              * Mathf.Deg2Rad;

                // Gaussian across the ray, so it has no sides.
                float across = Mathf.Exp(-(delta * delta) / (width[i] * width[i]));
                if (across < 0.004f) continue;

                // And squared along it, so the tip dissolves rather than stops.
                float along = Mathf.Clamp01(1f - radius / reach[i]);
                value += across * along * along * 0.85f;
            }

            return Mathf.Clamp01(value);
        });
    }

    // ---- the reward track's marks -------------------------------------------
    //
    // FIVE SHAPES, NOT TWELVE. The track pays twelve kinds of reward and every
    // node already carries its name in words, so an icon per kind would be
    // eleven pieces of bespoke art doing what the caption does. What the rail
    // needs instead is to be SCANNABLE without reading -- four grant marks that
    // differ at a glance, and one ring standing for "a capability", which is
    // what every milestone is.
    //
    // Drawn as strokes rather than glyphs on purpose. A tick or a star from the
    // font would rasterise into the dynamic atlas, and that atlas is tracked in
    // git -- AUDIT #47, where any run that draws a new glyph dirties a
    // committed asset.
    private static void BakeTrackMarks()
    {
        const int Size = 128;

        // The claimed tick. Two strokes, the short one falling and the long one
        // rising well past it, which is what makes a tick read as a tick rather
        // than as a bent line.
        //
        // NOTHING DRAWS THIS ANY MORE -- the reward track replaced its 14px
        // corner tick with the seal pip below, which knocks the same mark out
        // of a dark disc. Kept baked because CheckMark is now shared by both
        // and this is the one place the shape can be looked at on its own,
        // and because a check is the most reusable mark in the set.
        BakeGlow("track_tick", (nx, ny) => CheckMark(nx, ny, 0.11f));

        // A stat point: one chevron, pointing up.
        BakeGlow("track_stat", Size, (nx, ny) =>
        {
            float d = Mathf.Min(
                SegmentDistance(nx, ny, -0.42f, -0.16f, 0f, 0.30f),
                SegmentDistance(nx, ny, 0f, 0.30f, 0.42f, -0.16f));

            return Stroke(d, 0.12f);
        });

        // Experience: the same chevron twice, because it is the same idea
        // moving faster.
        BakeGlow("track_exp", Size, (nx, ny) =>
        {
            float upper = Mathf.Min(
                SegmentDistance(nx, ny, -0.40f, 0.02f, 0f, 0.42f),
                SegmentDistance(nx, ny, 0f, 0.42f, 0.40f, 0.02f));
            float lower = Mathf.Min(
                SegmentDistance(nx, ny, -0.40f, -0.34f, 0f, 0.06f),
                SegmentDistance(nx, ny, 0f, 0.06f, 0.40f, -0.34f));

            return Mathf.Max(Stroke(upper, 0.10f), Stroke(lower, 0.10f));
        });

        // Max health: a cross. Square-armed rather than a heart, which at 22px
        // is a blob.
        BakeGlow("track_health", Size, (nx, ny) =>
        {
            float d = Mathf.Min(
                SegmentDistance(nx, ny, -0.34f, 0f, 0.34f, 0f),
                SegmentDistance(nx, ny, 0f, -0.34f, 0f, 0.34f));

            return Stroke(d, 0.12f);
        });

        // Prince's Favor: an X.
        //
        // THIRD ATTEMPT, and the first two are worth recording because they
        // failed the same way. A four-point star fades its arms to nothing and
        // rendered as a dot; a filled diamond is crisp but a solid shape nine
        // pixels across is also a dot. What reads at this size is a STROKE --
        // which is why the chevron and the cross were legible from the first
        // capture and this was not. An X is the stroke that is not either of
        // them.
        BakeGlow("track_favor", Size, (nx, ny) =>
        {
            float d = Mathf.Min(
                SegmentDistance(nx, ny, -0.30f, -0.30f, 0.30f, 0.30f),
                SegmentDistance(nx, ny, -0.30f, 0.30f, 0.30f, -0.30f));

            return Stroke(d, 0.11f);
        });

        // THE DISC ITSELF, and it is a gradient rather than a flat fill.
        //
        // The rail used to draw proc:solid_circle tinted per state: a flat
        // #F2DB9E coin. Design's finding was that a flat gold disc reads as
        // TARNISH the moment anything is laid over it, because a flat fill has
        // no light in it for a texture to be light ON. This bakes the light in
        // -- one specular highlight at 32% across and 24% down, falling to a
        // dark rim -- and every state is that one sprite under a different
        // tint: dark violet for a level to come, gold for one reached, near
        // white for the player's own.
        //
        // WHITE-ISH RATHER THAN WHITE, which is the constraint a single tinted
        // sprite imposes: Image.color multiplies, so a value ramp can darken a
        // hue but cannot bend it. The handoff's pale disc runs #FFFFFF to
        // #CFC2E8, a shift toward violet that a grey ramp cannot make; the
        // controller tints it #F2ECFF instead and the rim lands near #C4BFD0.
        // Close, and the alternative is three baked discs to carry three hues.
        BakeShaded("disc_metal", Size, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);

            // The same antialiased edge solid_circle has, so the two read as
            // the same family of shape at the same size.
            float alpha = 1f - Mathf.Clamp01((radius - 0.92f) / 0.08f);

            // 32% across and 24% down, in the -1..1 frame the bake works in.
            const float HighlightX = -0.36f;
            const float HighlightY = 0.52f;

            float dx = nx - HighlightX;
            float dy = ny - HighlightY;
            float specular = Mathf.Exp(-(dx * dx + dy * dy) / (0.55f * 0.55f));

            // Floor at 0.52 rather than at zero: a disc whose rim goes black
            // reads as a hole, and the tint has to have something left to
            // colour down there.
            float value = Mathf.Lerp(0.52f, 1f, specular);

            // And a little extra darkening right at the rim, which is what
            // turns a lit circle into a struck one.
            value *= 1f - 0.12f * Smoothstep(Mathf.Clamp01(radius / 0.95f));

            return (value, alpha);
        });

        // A ONE-PIXEL RING, which ring_outline is not.
        //
        // That one is a soft annulus at 0.20 half-width -- the fight stage's
        // ground contact mark, deliberately blurred so an actor reads as
        // standing inside light rather than on a drawn circle. Everything the
        // track wants a ring for is the opposite: the milestone plate at inset
        // -7 and the waiting pulse are both HAIRLINES, and drawn with that
        // sprite they came out as a fog.
        //
        // Half-width 0.017 is one display pixel at the 58px the plate ring is
        // drawn at -- normalised 1.0 is half the sprite's width, so a stroke of
        // 2 x hw normalised measures hw x D pixels at display size D. The pulse
        // ring scales to about 92 and thickens to 1.6px on the way out, which
        // is what a ring dissipating should do anyway.
        Bake("ring_hairline", dist =>
        {
            const float Radius = 0.94f;
            const float HalfWidth = 0.017f;

            return Stroke(Mathf.Abs(dist - Radius), HalfWidth);
        });

        // THE NEXT CARET IS GONE, and unlike track_tick above it is not kept.
        //
        // It was a chevron pointing down at the node under it, and the argument
        // for the shape was sound: an arrow that points away from what it marks
        // points at the panel's edge instead. What killed it was where it had
        // to live. A centred caption block left one clear strip in the band,
        // 14px tall and a hundred pixels above the rail, so the caret sat there
        // -- and at 26x14, a hundred pixels from its node, it read as dust.
        //
        // The mark that replaced it is the word NEXT over a fading hairline,
        // which needs no sprite of its own beyond track_drop. track_tick stays
        // baked because its shape is shared with the seal pip and is the most
        // reusable mark in the set; a chevron pointing down is neither.

        // THE SEAL PIP'S GOLD HALF: a hairline ring at the rim with the claimed
        // check inside it. Drawn OVER a dark disc, which is solid_circle tinted
        // to the pip's own ground -- two nodes, not one.
        //
        // THE KNOCKOUT WENT THE OTHER WAY AND DID NOT READ, which is worth
        // recording because the argument for it was good. The pip only appears
        // on a collected node and a collected node's disc is gold metal, so a
        // check CUT OUT of a dark pip shows that gold through it at exactly the
        // light the disc is lit with -- one sprite, one node, and no second gold
        // to keep in step with the first.
        //
        // What that reasoning left out is the width of the hole. A knocked-out
        // stroke can only be as wide as the pip has room for, and on a filler
        // node the pip is 9px across: the check came out about a pixel wide,
        // against gold, inside a dark disc 9px across on a disc 26px across.
        // The first runtime capture shows eighty-seven nodes wearing what reads
        // as a dark smudge at four o'clock. The prototype draws the mark
        // POSITIVE at 2.2/14 of a 15px pip -- 2.4px of gold on near-black -- and
        // that is a stroke rather than a hairline crack.
        //
        // The ring is the design's 1px rim; it is what stops a dark disc on a
        // dark background dissolving on an unlit node.
        BakeGlow("seal_mark", Size, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);
            float rim = Stroke(Mathf.Abs(radius - 0.90f), 0.055f) * 0.6f;

            // The same two strokes track_tick draws, at 9/15 of the pip so the
            // check sits inside the ring rather than touching it.
            const float CheckScale = 15f / 9f;
            float check = CheckMark(nx * CheckScale, ny * CheckScale, 0.16f);

            return Mathf.Clamp01(rim + check);
        });

        // THE MILESTONE'S ORBIT: a hairline ring broken into eight arcs, turned
        // slowly by the controller.
        //
        // A CONTINUOUS RING CANNOT BE SEEN TO ROTATE, which is the whole reason
        // this is dashed rather than being the plate ring turned. Rotation only
        // reads where there is something to carry it, and a circle is the one
        // shape that looks identical at every angle.
        //
        // Eight arcs at a 0.55 duty cycle, each end feathered over a fifth of
        // its own gap: hard-ended dashes read as a dial or a loading spinner,
        // which is chrome, and feathered ones read as light travelling round a
        // circle, which is what a milestone is meant to feel like.
        BakeGlow("milestone_ring", Size, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);

            // 0.94 AND 0.017, WHICH ARE ring_hairline's OWN NUMBERS and have to
            // be: this sprite replaces that one at the same node and the same
            // size, so any difference in radius is a difference in where the
            // milestone's plate ring sits. Baked at 0.88 first, and the ring
            // came off its inset-7 station and landed on the disc's rim -- two
            // pixels, and it read as a ring drawn ON the coin rather than
            // around it.
            float ring = Stroke(Mathf.Abs(radius - 0.94f), 0.017f);
            if (ring <= 0f) return 0f;

            const int Arcs = 8;
            const float Duty = 0.55f;

            // 0..1 round the circle, then 0..1 within one arc's own slot.
            float turn = (Mathf.Atan2(ny, nx) / (Mathf.PI * 2f) + 1f) % 1f;
            float within = (turn * Arcs) % 1f;

            // Feathered at both ends of the lit part of the slot.
            const float Feather = Duty * 0.2f;
            float dash = Mathf.Min(within, Duty - within) / Feather;

            return ring * Mathf.Clamp01(dash);
        });

        // The travelling light on the rail. A soft band with no edge of its
        // own, stretched to 300px and walked across 19,000.
        //
        // UNIFORM ALONG y for the reason bar_track's header gives: this is
        // scaled horizontally at runtime, and anything that varies across the
        // axis being scaled distorts differently every frame.
        BakeGlow("shimmer_band", 64, (nx, ny) =>
            Mathf.Exp(-(nx * nx) / (0.42f * 0.42f)));

        BakeTrackGrounds();
    }

    // ---- the talent sky ---------------------------------------------------------
    //
    // The design's backdrop is nine CSS-animated layers. Three of them are
    // shapes this baker can make once and the screen can then simply MOVE:
    // star fields, a nebula wash and a vignette. What the design animates as a
    // filter -- the hue rotation -- was cut in its own handoff (§12), so
    // nothing here needs a shader.
    //
    // FOUR STAR FIELDS AS FOUR TEXTURES, not seventy-eight nodes. The design
    // authors 28 + 20 + 18 + 12 individual stars because a div is what it has;
    // a baked field pans and twinkles as one Image and reads identically at
    // 1px per star. The property the design actually cares about -- that the
    // fields never synchronise -- survives, because it lives in the periods
    // rather than in the stars.
    private static void BakeConstellation()
    {
        // Deterministic from an index: the baker must produce the same bytes
        // every run or WritePng's compare-before-write is defeated.
        BakeStarField("star_field_near", 512, count: 28, seed: 17, maxRadius: 1.6f, brightness: 1.0f);
        BakeStarField("star_field_mid", 512, count: 20, seed: 41, maxRadius: 1.1f, brightness: 0.85f);
        BakeStarField("star_field_mid_b", 512, count: 18, seed: 73, maxRadius: 1.1f, brightness: 0.8f);
        BakeStarField("star_field_far", 512, count: 12, seed: 109, maxRadius: 0.9f, brightness: 0.34f);

        // A NEBULA WASH: soft overlapping blooms rather than one radial. A
        // single gradient drifting reads as a spotlight moving; several at
        // different scales read as cloud.
        BakeGlow("cloud_wash", 256, (nx, ny) =>
        {
            float value = 0f;
            for (int i = 0; i < 5; i++)
            {
                float cx = Mathf.Sin(i * 12.9898f) * 0.62f;
                float cy = Mathf.Cos(i * 78.233f) * 0.55f;
                float spread = Mathf.Lerp(0.34f, 0.72f, Frac(i * 0.6180f));

                float dx = nx - cx;
                float dy = ny - cy;
                value += Mathf.Exp(-(dx * dx + dy * dy) / (spread * spread)) * 0.5f;
            }

            // Gone by the edge whatever the blooms did, so the layer has no
            // rectangle of its own when it drifts.
            float edge = 1f - Smoothstep(Mathf.Clamp01((Mathf.Max(Mathf.Abs(nx), Mathf.Abs(ny)) - 0.55f) / 0.45f));
            return Mathf.Clamp01(value) * edge;
        });

        // THE VIGNETTE, as an inverse of everything else here: opaque at the
        // frame and nothing in the middle. The design states it as an inset
        // shadow, which uGUI has no equivalent of -- this is that shadow drawn
        // as a sprite and stretched over the stage.
        BakeGlow("sky_vignette", 256, (nx, ny) =>
        {
            float d = Mathf.Sqrt(nx * nx * 0.78f + ny * ny);
            return Smoothstep(Mathf.Clamp01((d - 0.55f) / 0.62f)) * 0.92f;
        });

        // THE GATE COLLAR, as a ring thick enough to read a fill along. Drawn
        // with Image.type Filled / Radial360 by the controller, which is uGUI's
        // own conic gradient -- the design's arc is exactly a radial fill of a
        // ring, and needs no shader to say so.
        //
        // A NOTCH AT TWELVE O'CLOCK, because at 7/9 a plain conic looked like a
        // closed circle. The gap is where the count starts, so the arc has a
        // beginning as well as an end.
        Bake("collar_ring", dist =>
        {
            const float Radius = 0.86f;
            const float HalfWidth = 0.055f;

            return 1f - Smoothstep(Mathf.Clamp01(Mathf.Abs(dist - Radius) / HalfWidth));
        });

        BakeGlow("collar_notch", 64, (nx, ny) =>
        {
            // A wedge at the top, cut out of the collar by drawing over it in
            // the panel's own ground.
            float radius = Mathf.Sqrt(nx * nx + ny * ny);
            if (radius < 0.6f || radius > 1f) return 0f;

            return Mathf.Abs(nx) < 0.055f && ny > 0f ? 1f : 0f;
        });

        // A LIT STONE'S AURA: two soft arcs in a band, rotated by the
        // controller. It never changes size or brightness -- motion without
        // pulsing is the difference between "this is alive" and "you may press
        // this", and the pulse is reserved for the reachable ring.
        BakeGlow("orb_aura", 256, (nx, ny) =>
        {
            float radius = Mathf.Sqrt(nx * nx + ny * ny);
            float band = 1f - Smoothstep(Mathf.Clamp01(Mathf.Abs(radius - 0.84f) / 0.16f));
            if (band <= 0f) return 0f;

            // Two arcs, opposite each other, each feathered along its own
            // length so neither has an end.
            float turn = (Mathf.Atan2(ny, nx) / (Mathf.PI * 2f) + 1f) % 1f;
            float within = (turn * 2f) % 1f;
            float arc = Mathf.Exp(-Mathf.Pow((within - 0.5f) / 0.26f, 2f));

            return band * arc;
        });
    }

    // One field of stars, placed deterministically and drawn with a soft edge
    // so a 1px star does not alias into a square when the field pans.
    private static void BakeStarField(string name, int size, int count, int seed,
                                      float maxRadius, float brightness)
    {
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
        var pixels = new Color32[size * size];

        var xs = new float[count];
        var ys = new float[count];
        var rs = new float[count];
        var bs = new float[count];

        for (int i = 0; i < count; i++)
        {
            // Hashed rather than Random: same bytes every run.
            xs[i] = Frac(Mathf.Sin((i + seed) * 12.9898f) * 43758.5453f) * size;
            ys[i] = Frac(Mathf.Sin((i + seed) * 78.233f) * 12345.6789f) * size;
            rs[i] = Mathf.Lerp(0.55f, maxRadius, Frac((i + seed) * 0.6180f));
            bs[i] = Mathf.Lerp(0.5f, 1f, Frac((i + seed) * 0.3247f)) * brightness;
        }

        for (int y = 0; y < size; y++)
        {
            for (int x = 0; x < size; x++)
            {
                float value = 0f;

                for (int i = 0; i < count; i++)
                {
                    float dx = x + 0.5f - xs[i];
                    float dy = y + 0.5f - ys[i];
                    float d2 = dx * dx + dy * dy;

                    // Cheap reject: a star reaches about three radii.
                    float reach = rs[i] * 3f;
                    if (d2 > reach * reach) continue;

                    value += Mathf.Exp(-d2 / (rs[i] * rs[i])) * bs[i];
                }

                byte a = (byte)Mathf.RoundToInt(Mathf.Clamp01(value) * 255f);
                pixels[y * size + x] = new Color32(255, 255, 255, a);
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    // THE FOUR GROUNDS THE TRACK SITS ON, all of them gradients and all of them
    // gradients for the same reason: every one of these replaced a flat fill
    // that read as a printed block on a painted screen.
    //
    // A flat rect has an edge everywhere along it. That is fine for a button,
    // which is meant to have one, and wrong for a wash, a band, or a lit line,
    // which are meant to be light rather than paint -- and the only way to say
    // "no edge" in uGUI is to hand Image a sprite whose alpha falls off.
    private static void BakeTrackGrounds()
    {
        // THE RAIL BAND'S WASH. Vertical, dark in the middle and nothing at
        // either edge, so the band has no top or bottom line of its own -- the
        // two gold hairlines are the edge, and the wash is what fills between
        // them.
        //
        // sqrt of a triangle rather than a smoothstep, and the shape is fitted
        // rather than chosen: the design gives four stops, 0 at both edges,
        // 0.67 of peak at 22% and 78%, and peak at the middle. |2t-1| is the
        // triangle those points nearly lie on and the square root pulls it onto
        // them -- 0.44 becomes 0.66 against a specified 0.67.
        BakeGradient("band_fade", 128, ny =>
            (1f, Mathf.Sqrt(Mathf.Clamp01(1f - Mathf.Abs(ny * 2f - 1f)))));

        // A HAIRLINE THAT ENDS IN NOTHING. Full across the middle two thirds
        // and gone by the ends, which is what keeps a 1600px rule from meeting
        // the panel's own border at a hard T.
        //
        // Uniform along y: this is stretched to 1px tall and 1500 wide, and
        // anything varying across the axis being scaled resamples differently
        // at every canvas size.
        BakeGlow("hairline_fade", 64, (nx, ny) =>
            1f - Smoothstep(Mathf.Clamp01((Mathf.Abs(nx) - 0.64f) / 0.36f)));

        // THE LIT RAIL, brightening toward the player.
        //
        // A flat bar says "this much is done". A bar that gains light as it
        // travels says which END of it is now -- and on a rail 19,000px long
        // whose lit half can be 8,000 of them, that is the difference between a
        // progress bar and a path.
        //
        // ALPHA rather than value, which is the constraint a tinted sprite
        // imposes: the design runs #F2DB9E52 to #FFF3D6, gold warming to cream,
        // and a single Image.color cannot bend a hue along its own length. Gold
        // at rising opacity over this ground gets the brightening; the last two
        // percent of warmth is what it cannot have.
        BakeGlow("rail_ramp", 64, (nx, ny) =>
        {
            float t = Mathf.Clamp01((nx + 1f) * 0.5f);

            return t < 0.6f
                ? Mathf.Lerp(0.32f, 0.6f, t / 0.6f)
                : Mathf.Lerp(0.6f, 1f, (t - 0.6f) / 0.4f);
        });

        // And the bloom under it. The same ramp across, a gaussian down, so the
        // lit rail sits in light rather than on a second bar -- the design asks
        // for a 15px band at blur 5, and a blur is exactly what a baked falloff
        // is for.
        BakeGlow("rail_glow", 64, (nx, ny) =>
        {
            float t = Mathf.Clamp01((nx + 1f) * 0.5f);
            float across = t < 0.65f
                ? Mathf.Lerp(0.125f, 0.5f, t / 0.65f)
                : Mathf.Lerp(0.5f, 1f, (t - 0.65f) / 0.35f);

            return across * Mathf.Exp(-(ny * ny) / (0.55f * 0.55f));
        });

        // THE LINE UNDER THE WORD "NEXT", dissolving as it falls toward the
        // node it points at. Solid where it leaves the word and gone before it
        // arrives -- a line that stops dead above a disc reads as a join
        // between two things rather than as a direction.
        BakeGradient("track_drop", 32, ny => (1f, ny));

        // THE FOCUS CARD'S GROUND, lighter at its head than at its foot.
        //
        // The design's is a 158-degree linear gradient, #241735 to #120A18 --
        // very nearly vertical, and taken as vertical here because a diagonal
        // would need a rotated sprite and eight degrees is not worth one.
        //
        // A VALUE ramp, not an alpha one: this is opaque and sits over the
        // panel's own ground, so fading it would show that ground through and
        // make the card a tint rather than a plate. #120A18 is #241735 at very
        // nearly half brightness, which is why one tint and one ramp can say
        // both ends of it.
        BakeGradient("card_ground", 128, ny => (Mathf.Lerp(0.5f, 1f, ny), 1f));
    }

    // THE CHECK, as one shape with two customers.
    //
    // track_tick draws it whole and the seal pip knocks it out of a disc, and
    // the two used to carry the same four coordinates independently. Four
    // magic numbers copied once is how the short stroke and the long one drift
    // apart -- and a tick whose arms disagree between two sprites is the kind
    // of thing nobody looks at twice and everybody half-notices.
    private static float CheckMark(float nx, float ny, float halfWidth)
    {
        float d = Mathf.Min(
            SegmentDistance(nx, ny, -0.42f, 0.02f, -0.12f, -0.34f),
            SegmentDistance(nx, ny, -0.12f, -0.34f, 0.46f, 0.38f));

        return Stroke(d, halfWidth);
    }

    private static void BakeGlow(string name, Func<float, float, float> intensityAt) =>
        BakeGlow(name, Size, intensityAt);

    // Distance from (px,py) to the segment (ax,ay)-(bx,by), in the same
    // normalised space the bake lambdas work in.
    private static float SegmentDistance(float px, float py, float ax, float ay, float bx, float by)
    {
        float vx = bx - ax;
        float vy = by - ay;
        float wx = px - ax;
        float wy = py - ay;

        float lengthSquared = vx * vx + vy * vy;
        float t = lengthSquared <= 0f ? 0f : Mathf.Clamp01((wx * vx + wy * vy) / lengthSquared);

        float dx = wx - vx * t;
        float dy = wy - vy * t;
        return Mathf.Sqrt(dx * dx + dy * dy);
    }

    // A stroke of `halfWidth`, antialiased over the outer fifth of it so the
    // marks do not read as pixel art beside painted UI.
    private static float Stroke(float distance, float halfWidth)
    {
        float edge = halfWidth * 0.2f;
        return 1f - Smoothstep(Mathf.Clamp01((distance - (halfWidth - edge)) / edge));
    }

    private static float Frac(float value) => value - Mathf.Floor(value);

    // The experience bar: a recessed channel and the light that fills it.
    //
    // UNIFORM ALONG X, both of them, and that is the whole design decision.
    // The fill is stretched to whatever fraction of the track has been earned,
    // so anything that varies horizontally -- a rounded cap, a highlight at one
    // end -- distorts as the bar grows and, worse, distorts DIFFERENTLY every
    // frame while it animates. All the shaping is vertical; the ends are square
    // and the track's own art supplies the enclosure.
    private static void BakeBar()
    {
        // The channel. Dark, with the light caught along its top lip so it
        // reads as cut into the panel rather than drawn on top of it.
        //
        // The body used to run 0.10..0.22, which is nearly black BEFORE the
        // Reckoning multiplies it by a dark violet tint -- the two darknesses
        // compounded to roughly #08060E and the bar read as a hole punched in
        // the panel rather than as a groove cut into it. Raised so the tint has
        // something to colour: the shading still does the recessing, but the
        // result stays recognisably a surface.
        BakeGradient("bar_track", 64, y =>
        {
            // Light bouncing off the floor of the groove, and the highlight
            // caught on its top lip. Keeping BOTH is what stops a raised level
            // reading as a flat plate: bright, dip, bright is a section through
            // a channel, and a single ramp is not.
            float floorBounce = Mathf.Clamp01(1f - y / 0.22f);
            float lip = Mathf.Exp(-Mathf.Pow((y - 0.94f) / 0.05f, 2f));

            float value = Mathf.Lerp(0.30f, 0.46f, y) + floorBounce * 0.10f;
            return (Mathf.Clamp01(value + lip * 0.42f), 1f);
        });

        // The light the fill throws onto the panel around it.
        //
        // HOLLOW THROUGH THE MIDDLE, which is the whole trick. This is drawn as
        // a child of the fill and therefore ON TOP of it, so any alpha across
        // the bar itself would wash out the thing it is supposed to be lit by.
        // Zero for the width the fill occupies, rising just outside it, gone by
        // the edge -- a halo, not an overlay.
        //
        // The node is inset 12 beyond a 32-tall track, so the fill occupies the
        // middle 32/56 of this texture: everything inside d 0.57 must stay
        // empty, and 0.50 leaves margin for filtering.
        BakeGradient("bar_bloom", 96, y =>
        {
            float d = Mathf.Abs(y - 0.5f) * 2f;                  // 0 centre, 1 edge
            if (d <= 0.5f) return (1f, 0f);

            float t = Mathf.Clamp01((d - 0.5f) / 0.5f);
            float alpha = Smoothstep(Mathf.Clamp01(t / 0.2f)) * Mathf.Pow(1f - t, 1.8f);
            return (1f, alpha);
        });

        // The fill. White so it can be tinted twice from one asset -- once for
        // what was already earned and once, brighter, for what this fight paid.
        BakeGradient("bar_fill", 64, y =>
        {
            // Brightest just under the top edge, falling away downward: a bar
            // lit from above rather than a flat block of colour.
            //
            // The old numbers said bloom and drew a flat white strip. body ran
            // 0.55..0.95 and the bloom added up to 0.55 on top, so everything
            // above y 0.45 clamped to 1 -- five eighths of the bar was one
            // saturated value and the gradient was invisible. A bloom is a
            // bright CORE against something less bright; without the contrast
            // there is nothing to read as light.
            //
            // Lowered and narrowed so the core saturates over roughly a fifth
            // of the height and falls off on both sides of it.
            float bloom = Mathf.Exp(-Mathf.Pow((y - 0.80f) / 0.26f, 2f));
            float body = Mathf.Lerp(0.34f, 0.62f, y);

            // Softened at both edges so it never shows a hard line against the
            // channel it sits in -- and widened with the channel, since a
            // lighter track shows a hard fill edge that a near-black one hid.
            float edge = Mathf.Clamp01(Mathf.Min(y, 1f - y) / 0.10f);

            return (Mathf.Clamp01(body + bloom * 0.62f), edge);
        });
    }

    // The stage scrim: two of its three layers. The third is `radial_glow`,
    // already baked above and simply tinted dark -- a knock-down and a bloom
    // are the same shape, and only the colour differs.
    //
    // BOTH BAKED WHITE, with all the shaping in ALPHA. The scrim's colour is a
    // layout decision and belongs in the screen tree where it can be read next
    // to the palette it has to sit against; baking a dark pixel here would put
    // half the decision in an Editor script and make the tint a multiplier on
    // a number nobody can see.
    private static void BakeScrim()
    {
        // A band across the actor rows. Soft at BOTH edges over a wide
        // falloff: a scrim whose own boundary is visible has become a shape on
        // the screen, which is the one thing it must never be. 0.30 either side
        // leaves a flat 40% core doing the actual separating.
        BakeGradient("scrim_band", 128, y =>
        {
            float edge = Mathf.Clamp01(Mathf.Min(y, 1f - y) / 0.30f);
            return (1f, Smoothstep(edge));
        });

        // The dossier's own wash, brightest along the top edge.
        //
        // A flat ground gave that screen no hierarchy at all: three columns of
        // equal weight on one even field, and nothing telling the eye where to
        // start. Light falling from above is the cheapest fix that is also
        // true to the rest of the game's art -- every portrait and actor in
        // this project is lit from above, so a panel lit the same way sits in
        // the same world rather than looking like a web page behind them.
        //
        // Cubed falloff, not linear. Linear reads as a grey haze over the whole
        // panel; cubed keeps the bottom two thirds honest black and puts the
        // whole of the lift in the top third, where the portrait and the column
        // headings are.
        BakeGradient("dossier_veil", 128, y =>
        {
            float up = Mathf.Clamp01(y);
            return (1f, Smoothstep(up * up * up));
        });

        // Weighted to the bottom of the screen, under the command columns.
        // Squared rather than linear so it stays out of the way through the
        // middle of the frame and only bites where the HUD actually is --
        // a linear ramp put visible grey halfway up the backdrop.
        BakeGradient("scrim_floor", 128, y =>
        {
            float down = Mathf.Clamp01(1f - y);
            return (1f, Smoothstep(down * down));
        });
    }

    // The heat under the Continue arrow.
    //
    // THIS ONE BAKES ITS OWN COLOUR, and that is a departure from the rule the
    // scrim states two methods up -- there, colour is a layout decision and
    // belongs in the tree. Fire is not one colour. A flame is white-hot at the
    // core, orange through the body and deep red at the edge, and no single
    // Image tint can produce that from a greyscale ramp: multiplying white by
    // red gives red everywhere, with a brighter red where the core should be
    // white. The hue ramp is intrinsic to the thing being drawn. Intensity is
    // still the tree's: the node tints alpha and leaves the hues alone.
    //
    // NOT AN ELLIPSE. The brief was "not square or rectangular, it should feel
    // flowing and alive", so the radius is modulated by two out-of-phase sine
    // terms in the angle. Enough to break the silhouette; not so much that it
    // reads as a shape with lobes.
    private static void BakeEmber()
    {
        const int Width = 512;

        // 256 rather than 128. The vertical edge fade below spans a third of
        // the height and is then squeezed into an 88px box on screen, so the
        // ramp has about 29 screen pixels to happen in; at 128 rows it was
        // being reconstructed from 42 texture rows and banded visibly.
        const int Height = 256;
        string path = $"{GeneratedDir}/arrow_ember.png";

        var texture = new Texture2D(Width, Height, TextureFormat.RGBA32, false);
        var pixels = new Color32[Width * Height];

        // The core sits BACK ON THE ARROWHEAD, not at the point, and the whole
        // character of the effect turns on that one number.
        //
        // A core at the point can only ever produce a tail: the arrow is
        // opaque, so nothing behind it shows, and the glow starts where the art
        // stops. Pulled back to -0.18 the core is hidden under the head and
        // what remains visible is the halo AROUND it -- heat running the length
        // of the arrow, top and bottom, brightest at the head and trailing off
        // to the right. That is what makes it embrace the button instead of
        // pointing away from it.
        //
        // Every one of these was settled by compositing against the real arrow
        // and frame rather than reasoned about: a core at the point, a core
        // under the head with a tight vertical spread (a smudge), and a long
        // narrow version that read as jet exhaust, before this.
        const float CoreX = -0.18f;

        // Asymmetric on purpose: the tail runs further right than left.
        const float SpreadRight = 1.10f;
        const float SpreadLeft = 1.00f;

        // WIDE, and this is the other half of the embrace. At 1.25 the glow
        // fell off before it cleared the arrow's own silhouette, so it could
        // never be seen alongside the art -- only past the end of it. At 1.90
        // the falloff is gentle enough that the band of heat is still alive
        // where the arrow's top and bottom edges are.
        const float SpreadY = 1.90f;

        for (int y = 0; y < Height; y++)
        {
            for (int x = 0; x < Width; x++)
            {
                float nx = (x + 0.5f) / Width * 2f - 1f;
                float ny = (y + 0.5f) / Height * 2f - 1f;

                float dx = (nx - CoreX) / (nx >= CoreX ? SpreadRight : SpreadLeft);
                float dy = ny / SpreadY;

                float r = Mathf.Sqrt(dx * dx + dy * dy);
                float angle = Mathf.Atan2(dy, dx);
                float wobble = 1f
                    + 0.13f * Mathf.Sin(angle * 3f + 1.1f)
                    + 0.07f * Mathf.Sin(angle * 5f - 0.4f);
                r /= Mathf.Max(0.35f, wobble);

                float falloff = 1f - Smoothstep(Mathf.Clamp01(r));

                // 1.1, down from a squared falloff and then from 1.3. Each drop
                // buys tail: squared was a dot with nothing coming off it, and
                // anything above about 1.2 loses the far end of the band that
                // now runs alongside the arrow.
                float alpha = Mathf.Pow(falloff, 1.1f);

                // FADE THE OUTER THIRD TO NOTHING, and this is a fix rather
                // than a flourish. SpreadY is 1.90, which means the radial
                // falloff is nowhere near zero by the time it reaches the top
                // and bottom of the texture -- it was still at alpha 64 and 81
                // of 255 at the two edges, so the sprite ended in a hard
                // horizontal line and the glow read as a rectangle laid over
                // the panel. Widening the spread to wrap the arrow is what
                // caused it; the spread is right and the cut was the bug.
                //
                // 0.34, up from a first attempt at 0.10. A tenth was not a
                // gradient: it took alpha from 81 to 1 in six texture rows,
                // which is four pixels once this is squeezed into an 88px box,
                // and four pixels of ramp is still an edge. The fade has to
                // start where the glow is still strong to read as a fade at
                // all.
                //
                // It cannot start much earlier than this without eating the
                // band alongside the arrow that the whole widening was for --
                // the arrow's own silhouette reaches about |ny| 0.68, so the
                // fade begins just outside it.
                //
                // SQUARED, so the ramp leaves the full-strength region gently
                // and arrives at zero steeply. A plain smoothstep put its
                // steepest part in the middle of the ramp, which is exactly
                // where the eye reads a line.
                //
                // Applied on both axes, even though only the vertical one was
                // visibly wrong: the next change to a spread should not be able
                // to reintroduce this.
                float fadeY = Smoothstep(Mathf.Clamp01((1f - Mathf.Abs(ny)) / 0.34f));
                float fadeX = Smoothstep(Mathf.Clamp01((1f - Mathf.Abs(nx)) / 0.10f));
                alpha *= fadeY * fadeY * fadeX;

                // White-hot core -> orange -> deep red, keyed off the same
                // falloff so the hottest pixel is also the brightest.
                float hot = Mathf.Clamp01((falloff - 0.55f) / 0.45f);
                float mid = Mathf.Clamp01(falloff / 0.55f);

                float red = Mathf.Lerp(0.77f, 1f, mid);
                float green = Mathf.Lerp(0.12f, 0.48f, mid) + hot * 0.46f;
                float blue = Mathf.Lerp(0.03f, 0.12f, mid) + hot * 0.62f;

                pixels[y * Width + x] = new Color32(
                    (byte)Mathf.RoundToInt(Mathf.Clamp01(red) * 255f),
                    (byte)Mathf.RoundToInt(Mathf.Clamp01(green) * 255f),
                    (byte)Mathf.RoundToInt(Mathf.Clamp01(blue) * 255f),
                    (byte)Mathf.RoundToInt(Mathf.Clamp01(alpha) * 255f));
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    // A bar-shaped sprite that varies only with height. `shade` returns
    // (brightness, alpha) for a normalised y, 0 at the bottom.
    private static void BakeGradient(string name, int height, Func<float, (float value, float alpha)> shade)
    {
        const int Width = 16;   // uniform across, so this only has to be wide
                                // enough to survive filtering
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(Width, height, TextureFormat.RGBA32, false);
        var pixels = new Color32[Width * height];

        for (int y = 0; y < height; y++)
        {
            var (value, alpha) = shade((y + 0.5f) / height);
            byte channel = (byte)Mathf.RoundToInt(Mathf.Clamp01(value) * 255f);
            byte a = (byte)Mathf.RoundToInt(Mathf.Clamp01(alpha) * 255f);

            for (int x = 0; x < Width; x++)
            {
                pixels[y * Width + x] = new Color32(channel, channel, channel, a);
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    // White pixels whose ALPHA is the intensity. No rim and no signed
    // distance: a glow is a field, not a shape with an edge.
    private static void BakeGlow(string name, int size, Func<float, float, float> intensityAt)
    {
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
        var pixels = new Color32[size * size];

        for (int y = 0; y < size; y++)
        {
            for (int x = 0; x < size; x++)
            {
                float nx = (x + 0.5f) / size * 2f - 1f;
                float ny = (y + 0.5f) / size * 2f - 1f;

                float alpha = Mathf.Clamp01(intensityAt(nx, ny));
                pixels[y * size + x] = new Color32(255, 255, 255, (byte)Mathf.RoundToInt(alpha * 255f));
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    // Greyscale VALUE and alpha, both varying in two dimensions.
    //
    // The third bake shape, and it exists because the disc needed something
    // neither of the other two can say. Bake is white with a radial alpha -- a
    // silhouette, tintable but flat. BakeGradient carries value but only along
    // one axis, which is right for a bar and useless for a specular highlight
    // that sits off-centre in both. This is the two of them at once.
    private static void BakeShaded(string name, int size, Func<float, float, (float value, float alpha)> shade)
    {
        string path = $"{GeneratedDir}/{name}.png";

        var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
        var pixels = new Color32[size * size];

        for (int y = 0; y < size; y++)
        {
            for (int x = 0; x < size; x++)
            {
                float nx = (x + 0.5f) / size * 2f - 1f;
                float ny = (y + 0.5f) / size * 2f - 1f;

                var (value, alpha) = shade(nx, ny);
                byte channel = (byte)Mathf.RoundToInt(Mathf.Clamp01(value) * 255f);
                byte a = (byte)Mathf.RoundToInt(Mathf.Clamp01(alpha) * 255f);

                pixels[y * size + x] = new Color32(channel, channel, channel, a);
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng(path, texture);
    }

    private static float Smoothstep(float x) => x * x * (3f - 2f * x);

    // A radially symmetric shape: alpha as a function of distance from centre,
    // white throughout so every use site can tint it.
    private static void Bake(string name, Func<float, float> alphaAtDistance)
    {
        var texture = new Texture2D(Size, Size, TextureFormat.RGBA32, false);
        var pixels = new Color32[Size * Size];

        for (int y = 0; y < Size; y++)
        {
            for (int x = 0; x < Size; x++)
            {
                float nx = (x + 0.5f) / Size * 2f - 1f;
                float ny = (y + 0.5f) / Size * 2f - 1f;
                float alpha = Mathf.Clamp01(alphaAtDistance(Mathf.Sqrt(nx * nx + ny * ny)));
                pixels[y * Size + x] = new Color32(255, 255, 255, (byte)Mathf.RoundToInt(alpha * 255f));
            }
        }

        texture.SetPixels32(pixels);
        texture.Apply();
        WritePng($"{GeneratedDir}/{name}.png", texture);
    }

    // Encode, compare, write, import. One place that knows the importer
    // settings a Sprite needs.
    private static void WritePng(string path, Texture2D texture)
    {
        var png = texture.EncodeToPNG();
        UnityEngine.Object.DestroyImmediate(texture);

        // Byte-compare before writing: an unchanged PNG must not be rewritten,
        // or every build churns the file and every diff is noise.
        //
        // THE IMPORT SETTINGS ARE CHECKED EITHER WAY. They live in the .meta,
        // not in the pixels, so gating them on the pixels having changed makes
        // them unfixable for every sprite already on disk.
        if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(png))
        {
            Import(path);
            return;
        }

        File.WriteAllBytes(path, png);
        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);

        Import(path);
        Debug.Log($"[ProceduralSpriteBaker] baked {path}");
    }

    // THE IMPORTER SETTINGS EVERY BAKED SPRITE NEEDS, applied whether or not the
    // PNG itself changed.
    //
    // Outside the byte-compare above, deliberately: the compare exists to stop
    // an unchanged PNG churning in git, and it used to skip the import block
    // with it. That made the settings unfixable -- changing what a baked sprite
    // should be imported as did nothing to the twenty-odd already on disk,
    // because their pixels had not moved.
    // THE SPRITES DRAWN AS BARS rather than as shapes, which is the one set
    // mipmaps must not be turned on for.
    //
    // A mip level is chosen from the LARGER of the two axis derivatives, so a
    // 64px texture stretched to 1512x1 is sampled as though it were downscaled
    // 64 times -- mip 6, which is a single texel. The horizontal fade that is
    // the whole point of hairline_fade would come back as a flat line. The lit
    // rail's ramp, 19,000 wide and 3 tall, goes the same way.
    //
    // Anisotropic filtering is the textbook answer and is not taken here: it
    // would have to be raised on every one of these, it is capped by the
    // project's quality settings rather than by this file, and the thing it
    // buys back is detail along an axis where these textures have none to spare
    // anyway. A stretched gradient has no high-frequency content for a mip
    // chain to protect it from -- which is the same reason it never looked
    // grainy and is not what this change is for.
    private static readonly HashSet<string> DrawnAsBars = new HashSet<string>
    {
        "hairline_fade", "rail_ramp", "rail_glow", "shimmer_band", "track_drop",
        "band_fade", "card_ground", "soft_edge_stripe",
        "bar_track", "bar_fill", "bar_bloom",
        "scrim_band", "dossier_veil", "scrim_floor",
    };

    private static void Import(string path)
    {
        var importer = AssetImporter.GetAtPath(path) as TextureImporter;
        if (importer == null) return;

        bool mip = !DrawnAsBars.Contains(Path.GetFileNameWithoutExtension(path));

        // The mesh type lives on TextureImporterSettings rather than on the
        // importer itself, so it has to be read out, changed and written back.
        var settings = new TextureImporterSettings();
        importer.ReadTextureSettings(settings);

        // Without Sprite + alphaIsTransparency, LoadAssetAtPath<Sprite> returns
        // null with no error anywhere - the failure that shipped a spell playing
        // nothing for weeks in v1.
        bool wrong =
            importer.textureType != TextureImporterType.Sprite
            || importer.spriteImportMode != SpriteImportMode.Single
            || !importer.alphaIsTransparency
            || importer.mipmapEnabled != mip
            || importer.filterMode != FilterMode.Trilinear
            || importer.textureCompression != TextureImporterCompression.Uncompressed
            || settings.spriteMeshType != SpriteMeshType.FullRect;

        if (!wrong) return;

        importer.textureType = TextureImporterType.Sprite;
        importer.spriteImportMode = SpriteImportMode.Single;
        importer.alphaIsTransparency = true;

        // MIPMAPS, WHICH THIS EXPLICITLY TURNED OFF.
        //
        // Off is the usual advice for UI, and the usual advice assumes UI art
        // drawn at roughly the size it was authored. None of this is: every
        // shape here is baked at 128 or 1024 and drawn at 15 to 60. A reward
        // mark is 128px of texture in 15px of screen, so bilinear samples four
        // texels out of every seventy-two and the other sixty-eight are simply
        // not in the result -- which is what "grainy" is. It moves as the disc
        // scales on hover, because a different four texels win.
        //
        // Trilinear rather than bilinear for the same reason: the discs scale
        // 1.16x on hover and the pulse rings scale to 2.1x, so they cross mip
        // levels while moving, and a hard switch between two mips is a visible
        // pop mid-animation.
        importer.mipmapEnabled = mip;
        importer.filterMode = FilterMode.Trilinear;

        // UNCOMPRESSED, and affordable precisely because these are small: the
        // whole generated set is 27 files, none bigger than 1024 and most 128
        // square. Every one of them is a smooth gradient or a soft-edged
        // stroke, which is the worst case for block compression -- DXT quantises
        // each 4x4 block to two endpoints, so a gold ramp comes back as bands
        // and a 1px hairline comes back chewed.
        importer.textureCompression = TextureImporterCompression.Uncompressed;

        // FullRect, not Tight: a tight mesh traces the alpha and cuts the faint
        // outer edge off a glow, which is the part of a glow that does the work.
        //
        // Written through the settings object because the importer has no
        // property for it -- and the settings have to be re-read AFTER the
        // fields above are set, or writing them back would put the old values
        // over the top of what was just assigned.
        importer.ReadTextureSettings(settings);
        settings.spriteMeshType = SpriteMeshType.FullRect;
        importer.SetTextureSettings(settings);

        importer.SaveAndReimport();
    }
}
